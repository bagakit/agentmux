import { readFile, readdir, writeFile } from 'node:fs/promises'
import { parseDocument } from 'yaml'

const directory = new URL('../protocols/', import.meta.url)
const destination = new URL('../src/generated/amux-protocols.ts', import.meta.url)
const suffix = '.amux.prompt.md'
const slot = /\{\{([a-z][a-zA-Z0-9]*)\}\}/gu
const name = /^[a-z][a-z0-9-]*$/u
const forms = ['envelope', 'marker', 'frame', 'link', 'extension', 'prompt']
const entries = (await readdir(directory, { withFileTypes: true }))
  .filter(entry => entry.name.endsWith(suffix)).sort((a, b) => a.name.localeCompare(b.name, 'en'))
if (!entries.length) throw new Error('No AMUX protocol templates found.')

const definitions = {}, templates = {}, parameters = {}, examples = {}
const literal = value => JSON.stringify(value, null, 2)
for (const entry of entries) {
  const id = entry.name.slice(0, -suffix.length)
  if (!entry.isFile() || !name.test(id)) throw new Error('Invalid AMUX template source: ' + entry.name)
  const source = await readFile(new URL(entry.name, directory), 'utf8')
  const frontmatter = /^---\n([\s\S]*?)\n---\n/u.exec(source)
  const parsed = frontmatter && parseDocument(frontmatter[1], { uniqueKeys: true })
  const data = parsed?.toJS()
  if (!parsed || parsed.errors.length || !data || Object.keys(data).some(key => !['tag', 'form', 'title', 'description', 'examples'].includes(key))) {
    throw new Error('Invalid AMUX metadata: ' + id)
  }
  const { examples: samples, ...definition } = data
  if (['tag', 'title', 'description'].some(field => typeof definition[field] !== 'string' || !definition[field].trim()) || !forms.includes(definition.form)) {
    throw new Error('Invalid AMUX definition: ' + id)
  }
  definitions[id] = definition
  const members = {}, slots = {}
  for (const [, variant, text] of source.slice(frontmatter[0].length).matchAll(/^## ([a-z][a-z0-9-]*)\n\n~~~text\n([\s\S]*?)\n~~~$/gmu)) {
    if (Object.hasOwn(members, variant) || !text.trim() || /\{\{|\}\}/u.test(text.replace(slot, ''))) throw new Error('Invalid AMUX variant: ' + id + '/' + variant)
    members[variant] = text
    slots[variant] = [...new Set([...text.matchAll(slot)].map(match => match[1]))]
  }
  if (!Object.keys(members).length) throw new Error('No AMUX text variants: ' + id)
  templates[id] = members
  parameters[id] = slots
  if (!Array.isArray(samples) || !samples.length) throw new Error('AMUX examples are required: ' + id)
  examples[id] = samples.map(({ label, template, parameters: values = {}, after = '' }) => {
    if (typeof label !== 'string' || !Object.hasOwn(members, template) || typeof after !== 'string' ||
        Object.keys(values).length !== slots[template].length || slots[template].some(key => !Object.hasOwn(values, key))) {
      throw new Error('Invalid AMUX example: ' + id)
    }
    const params = Object.fromEntries(Object.entries(values).map(([key, value]) => {
      if (typeof value === 'string') return [key, value]
      if (value && Object.keys(value).join() === 'template' && Object.hasOwn(members, value.template) && slots[value.template].length === 0) return [key, members[value.template]]
      throw new Error('Invalid AMUX example parameter: ' + id + '/' + key)
    }))
    return { label, template, parameters: params, ...(after ? { after } : {}) }
  })
}

const output = '// Generated by scripts/generate-amux-protocols.mjs from protocols/. Do not edit.\n' +
  'export const AMUX_PROTOCOL_DEFINITIONS = ' + literal(definitions) + ' as const\n\n' +
  'export const AMUX_PROTOCOL_TEMPLATES = ' + literal(templates) + ' as const\n\n' +
  'export const AMUX_PROTOCOL_PARAMETERS = ' + literal(parameters) + ' as const\n\n' +
  'export const AMUX_PROTOCOL_EXAMPLES = ' + literal(examples) + ' as const\n'
let previous
try { previous = await readFile(destination, 'utf8') } catch (error) { if (error.code !== 'ENOENT') throw error }
if (process.argv.includes('--check')) {
  if (previous !== output) throw new Error('Generated AMUX templates are stale. Run node scripts/generate-amux-protocols.mjs.')
} else if (previous !== output) await writeFile(destination, output)
console.log('Compiled ' + entries.length + ' AMUX protocol sources.')
