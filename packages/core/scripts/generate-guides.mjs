import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises'
import { dirname, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { parseDocument } = require('yaml')
const packageRoot = fileURLToPath(new URL('../', import.meta.url))
const guidesRoot = resolve(packageRoot, 'guides')
const destination = resolve(packageRoot, 'src/generated/agentmux-guides.ts')
const check = process.argv.slice(2).includes('--check')
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: generate-guides.mjs [--check]')

const documents = new Map(), modules = {}
async function discover(directory) {
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const file = resolve(directory, entry.name)
    if (entry.isSymbolicLink()) throw new Error('Guide sources cannot be symlinks: ' + relative(guidesRoot, file))
    if (entry.isDirectory()) await discover(file)
    else if (entry.name.endsWith('.md') && entry.name !== 'README.md') {
      const id = relative(guidesRoot, file).split(sep).join('/').slice(0, -3)
      const source = await readFile(file, 'utf8')
      const frontmatter = /^---\n([\s\S]*?)\n---\n/u.exec(source)
      const parsed = frontmatter ? parseDocument(frontmatter[1], { uniqueKeys: true }) : null
      if (parsed?.errors.length) throw new Error('Invalid guide metadata: ' + id + ': ' + parsed.errors[0].message)
      const metadata = parsed?.toJS() ?? {}
      const marker = '<!-- amux:content -->\n'
      const contentStart = source.indexOf(marker)
      if (contentStart < 0 || source.indexOf(marker, contentStart + marker.length) >= 0) throw new Error('One content marker is required: ' + id)
      const body = source.slice(contentStart + marker.length).replace(/\n$/u, '')
      if (!body.trim()) throw new Error('Guide content is empty: ' + id)
      if (id.startsWith('modules/')) {
        const root = id.slice('modules/'.length)
        if (!/^[a-z][a-z0-9-]*$/u.test(root) || Object.keys(metadata).sort().join(',') !== 'roles,summary,when' ||
          ['summary', 'roles', 'when'].some(key => typeof metadata[key] !== 'string' || !metadata[key].trim())) throw new Error('Invalid module metadata: ' + id)
        modules[root] = { ...metadata, guide: id }
      } else if (Object.keys(metadata).length) throw new Error('Only module guides declare metadata: ' + id)
      documents.set(id, { file, body })
    }
  }
}
await discover(guidesRoot)
if (!documents.size || !Object.keys(modules).length) throw new Error('No system guides or modules were discovered')

// The only composition syntax is an ordinary Markdown link with one of these titles.
// Readers can follow the same source/owner link without running the CLI.
const directive = /\[([^\]\n]+)\]\(([^\s)]+) "amux:(include|generated)(?: ([a-z][a-z0-9:.-]*))?"\)/gu
const generatedSlots = new Set(['module-directory', 'module-root', 'goal-skill-entry', 'self-context-verb', 'protocol-catalog',
  'browser-capability-examples', 'browser-capability-directory', 'goal-manager-context'])
function expand(id, stack = []) {
  const document = documents.get(id)
  if (!document) throw new Error('Unknown guide include: ' + id)
  if (stack.includes(id)) throw new Error('Cyclic guide include: ' + [...stack, id].join(' -> '))
  return document.body.replace(directive, (original, _label, href, kind, slot) => {
    const target = resolve(dirname(document.file), href)
    if (kind === 'include') {
      const path = relative(guidesRoot, target).split(sep).join('/')
      if (slot || path.startsWith('../') || !path.endsWith('.md')) throw new Error('Invalid include in ' + id)
      return expand(path.slice(0, -3), [...stack, id])
    }
    if (!slot || !(generatedSlots.has(slot) || /^command:[a-z]+(?:\.[a-z][a-z0-9-]*)+$/u.test(slot))) throw new Error('Unknown generated guide slot in ' + id + ': ' + slot)
    return `<!-- amux:generated ${slot} -->`
  })
}
const texts = Object.fromEntries([...documents.keys()].sort().map(id => [id, expand(id)]))
for (const [id, text] of Object.entries(texts)) if (text.includes('"amux:')) throw new Error('Unresolved guide directive: ' + id)
const slots = Object.fromEntries(Object.entries(texts).map(([id, text]) => [id,
  [...new Set([...text.matchAll(/<!-- amux:generated ([a-z][a-z0-9:.-]*) -->/gu)].map(match => match[1]))].sort()]))
const output = '// Generated by scripts/generate-guides.mjs from guides/. Do not edit.\n' +
  'export type GuideId = ' + Object.keys(texts).map(id => JSON.stringify(id)).join(' | ') + '\n\n' +
  'export const GUIDE_DOCUMENTS: Readonly<Record<GuideId, string>> = ' + JSON.stringify(texts, null, 2) + '\n\n' +
  'export type GuideSlots = {\n' + Object.entries(slots).map(([id, names]) =>
    '  ' + JSON.stringify(id) + ': ' + (names.map(name => JSON.stringify(name)).join(' | ') || 'never')).join('\n') + '\n}\n\n' +
  'export const MODULE_GUIDES = ' + JSON.stringify(modules, null, 2) + ' as const\n'
let previous
try { previous = await readFile(destination, 'utf8') } catch (error) { if (error.code !== 'ENOENT') throw error }
if (check && previous !== output) throw new Error('Generated system guides are stale. Run pnpm --filter @agentmux/core generate:guides.')
if (!check && previous !== output) { await mkdir(dirname(destination), { recursive: true }); await writeFile(destination, output) }
console.log(`${check ? 'Checked' : 'Generated'} ${documents.size} guide documents and ${Object.keys(modules).length} modules.`)
