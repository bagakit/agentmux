const assert = require('node:assert/strict')

exports.run = async function run(p) {
  const { win, read, q, until, settle, click, field, type, scene, capture, section, owner, result } = p
  const originalPrompts = structuredClone(owner.current.composerShortcuts)
  const input = q('[aria-label="Find a command or shortcut"]')
  const rows = () => read(`(()=>{const pane=document.querySelector('[data-keyboard-shortcuts]');return [...(pane?.querySelectorAll('[data-binding-id]')??[])].filter(n=>n.checkVisibility()).map(n=>({id:n.dataset.bindingId,label:n.querySelector('.keyboard-shortcuts__label').textContent,keys:[...n.querySelectorAll('kbd')].map(k=>k.textContent),rect:n.getBoundingClientRect().toJSON()}))})()`)
  const focus = () => read(`(()=>{const n=document.activeElement;return{connected:!!n?.isConnected,visible:!!n?.checkVisibility(),hidden:!!n?.closest('[hidden],[inert]'),label:n?.getAttribute('aria-label'),tag:n?.tagName}})()`)
  const validFocus = async () => { const actual = await focus(); assert.ok(actual.connected && actual.visible && !actual.hidden && actual.tag !== 'BODY', 'Shortcuts focus is connected and visible'); return actual }
  const expected = await read('window.promptsProbe.shortcuts()')
  assert.ok(expected.bindings.length > 0, 'The actual complete registry is nonempty')
  result.registry = expected
  const help = expected.bindings.find(binding => binding.id === 'help.shortcuts')
  assert.ok(help, 'A real registry help binding exists')
  const chord = expected.isMac ? help.mac : help.other
  const modifiers = [...(chord.primary ? [expected.isMac ? 'meta' : 'control'] : []), ...(chord.shift ? ['shift'] : []), ...(chord.alt ? ['alt'] : [])]
  async function nativeHelp() {
    await read(`window.shortcutsNativeEvents=[];window.shortcutsNativeObserver=event=>window.shortcutsNativeEvents.push({key:event.key,code:event.code,isTrusted:event.isTrusted,isComposing:event.isComposing,keyCode:event.keyCode,defaultPrevented:event.defaultPrevented});document.addEventListener('keydown',window.shortcutsNativeObserver,{capture:true,passive:true})`)
    try {
      win.webContents.sendInputEvent({ type: 'keyDown', keyCode: chord.key === '?' ? '/' : chord.key, modifiers })
      win.webContents.sendInputEvent({ type: 'keyUp', keyCode: chord.key === '?' ? '/' : chord.key, modifiers })
      await settle()
      const events = await read('window.shortcutsNativeEvents')
      assert.ok(events.length > 0 && events.some(event => event.isTrusted && event.key.toLowerCase() === chord.key), 'The private renderer received the actual trusted registry help key')
      result.nativeHelp = events
      assert.equal(await read('document.querySelector(".settings-page")?.dataset.settingsPage'), 'keyboard-shortcuts', 'Keyboard help opens the same Settings section')
      await validFocus()
    } finally { await read("document.removeEventListener('keydown',window.shortcutsNativeObserver,{capture:true})") }
  }
  async function completeRows(message = 'Settings rows are the complete actual registry set') {
    const actual = await rows()
    assert.ok(actual.length > 0, message === 'Settings rows are the complete actual registry set' ? 'Actual shortcut row collection is nonempty' : message)
    assert.deepEqual(actual.map(row => row.id).sort(), expected.bindings.map(binding => binding.id).sort(), message)
    for (const binding of expected.bindings) {
      const row = actual.find(row => row.id === binding.id)
      assert.deepEqual(row.keys, binding.keys, 'Settings displays the actual registry platform chord')
      assert.equal(row.label, binding.label)
    }
    return actual
  }
  win.showInactive()
  await type(field('Prompt'), 'Original unsaved 中文 prompt draft')
  await win.webContents.debugger.sendCommand('Input.imeSetComposition', { text: '输入', selectionStart: 2, selectionEnd: 2 })
  await win.webContents.debugger.sendCommand('Input.insertText', { text: '输入' })
  await settle()
  for (let i = 0; i < 4; i++) {
    win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Left', modifiers: ['shift'] })
    win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Left', modifiers: ['shift'] })
  }
  await settle()
  result.promptBefore = await read(`(()=>{const node=${field('Prompt')};window.shortcutsPrompt={node,value:node.value,start:node.selectionStart,end:node.selectionEnd};return{value:node.value,start:node.selectionStart,end:node.selectionEnd,focused:node===document.activeElement}})()`)
  assert.equal(result.promptBefore.focused, true)
  assert.ok(result.promptBefore.value.includes('Original unsaved') && result.promptBefore.value.includes('输入'))
  assert.ok(result.promptBefore.end > result.promptBefore.start, 'Native Shift-arrow selected an actual draft range')
  await nativeHelp()
  result.completeRows = await completeRows()
  assert.equal(await read('!!document.querySelector(".shortcuts-help__overlay")'), false, 'The old shortcuts overlay is gone')
  await section('prompts')
  result.promptAfter = await read(`(()=>{const node=${field('Prompt')},before=window.shortcutsPrompt;return{sameNode:node===before.node,value:node.value,start:node.selectionStart,end:node.selectionEnd}})()`)
  assert.equal(result.promptAfter.sameNode, true, 'Help reroute preserves the actual Prompt textarea')
  assert.equal(result.promptAfter.value, result.promptBefore.value)
  assert.deepEqual([result.promptAfter.start, result.promptAfter.end], [result.promptBefore.start, result.promptBefore.end])
  assert.deepEqual(owner.current.composerShortcuts, originalPrompts, 'Read-only shortcuts never persist the draft')

  await section('overview')
  await click(q('[data-settings-section="keyboard-shortcuts"]'))
  assert.equal(await read('document.querySelector(".settings-page").dataset.settingsPage'), 'keyboard-shortcuts', 'Overview opens the registered shortcut pane')
  await completeRows()
  await section('general')
  await click(q('nav[aria-label="Settings sections"] [data-settings-target="keyboard-shortcuts"]'))
  assert.equal(await read('document.querySelector(".settings-page").dataset.settingsPage'), 'keyboard-shortcuts', 'Settings navigation opens the registered shortcut pane')
  await completeRows()
  await type(q('[aria-label="Search settings"]'), 'shortcuts')
  await completeRows('Settings title search keeps the full registry row set')
  await capture('1480-dark-shortcuts-title.png', 'Actual global title search finds a complete read-only registry page')
  await click(q('[aria-label="Clear settings search"]'))
  await type(input, 'save')
  const savedRows = await rows(), expectedSaved = expected.bindings.filter(binding => binding.label.toLowerCase().includes('save'))
  assert.ok(expectedSaved.length > 0)
  assert.deepEqual(savedRows.map(row => row.id), expectedSaved.map(binding => binding.id), 'Local command search filters actual registry rows')
  await capture('1480-dark-shortcuts-command.png', 'Local command search has one distinct responsibility')
  await type(input, 'unmatched-command-query')
  assert.deepEqual(await rows(), [])
  await validFocus()
  await capture('1480-dark-shortcuts-empty.png', 'Actual local no-result state with connected visible search focus')
  await click(q('[aria-label="Clear shortcut search"]'))
  assert.equal((await focus()).label, 'Find a command or shortcut', 'Clear restores the original connected command input')
  await completeRows()
  await capture('1480-dark-shortcuts-full.png', 'Complete registry, native platform chords and honest scope groups')
  result.scrollBefore = await read(`(()=>{const n=document.querySelector('[data-settings-pane="keyboard-shortcuts"]');return{top:n.scrollTop,height:n.scrollHeight,client:n.clientHeight,overflow:getComputedStyle(n).overflowY}})()`)
  assert.ok(result.scrollBefore.height > result.scrollBefore.client && ['auto','scroll'].includes(result.scrollBefore.overflow), 'Actual Settings pane has a nonempty scroll range')
  await read(`document.querySelector('[data-settings-pane="keyboard-shortcuts"]').scrollTo({top:${result.scrollBefore.height},behavior:'instant'})`)
  await settle()
  result.scrollAfter = await read(`(()=>{const n=document.querySelector('[data-settings-pane="keyboard-shortcuts"]'),last=[...n.querySelectorAll('[data-binding-id]')].at(-1),r=n.getBoundingClientRect(),b=last.getBoundingClientRect();return{top:n.scrollTop,max:n.scrollHeight-n.clientHeight,lastId:last.dataset.bindingId,lastVisible:b.top<r.bottom&&b.bottom>r.top}})()`)
  assert.ok(result.scrollAfter.top > result.scrollBefore.top && Math.abs(result.scrollAfter.top - result.scrollAfter.max) <= 1 && result.scrollAfter.lastVisible, 'Real Settings scrolling reveals an actual lower registry row')
  await capture('1480-dark-shortcuts-scopes.png', 'Real pane scroll reveals the lower registry scopes; this is not an OS wheel claim')
  await read(`document.querySelector('[data-settings-pane="keyboard-shortcuts"]').scrollTo({top:0,behavior:'instant'})`)
  await settle()
  assert.equal(await read(`document.querySelector('[data-settings-pane="keyboard-shortcuts"]').scrollTop`), 0, 'Real Settings scroll restores the first registry group')
  await scene(1480, 'light')
  await capture('1480-light-shortcuts-full.png', 'Full light Settings page with the actual longest command labels')
  await scene(320, 'dark')
  await completeRows()
  await validFocus()
  await capture('320-dark-shortcuts-full.png', 'Actual narrow Settings section, wrapping command labels and readable keys')
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await settle()
  await completeRows()
  assert.equal(await read("matchMedia('(prefers-reduced-motion: reduce)').matches"), true, 'Known reduce signal, not an OS preference claim')
  await capture('320-dark-shortcuts-reduced.png', 'Reduced motion keeps the same static readable commands')
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [] })
  await scene(1480, 'dark')
  await click(q('[aria-label="Close settings"]'))
  assert.equal(await read('!!document.querySelector(".settings-page")'), false)
  await click(q('.window-status-bar [data-shortcut-help-open]'))
  assert.equal(await read('document.querySelector(".settings-page")?.dataset.settingsPage'), 'keyboard-shortcuts', 'The original visible button opens the same Settings section')
  await validFocus()
  await completeRows()
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' })
  win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Escape' })
  await settle()
  assert.equal(await read('!!document.querySelector(".settings-page")'), false, 'Native Escape exits the original Settings owner')
  const returned = await validFocus()
  assert.equal(returned.label, 'Keyboard shortcuts', 'Settings exit returns focus to its visible original button')
  assert.deepEqual(owner.current.composerShortcuts, originalPrompts)
  result.boundary = 'Actual App, private ConfigOwner and trusted mac-host renderer input; actual CDP composition/draft retained. Both platform projection and IME/native consumption guards are additionally covered by bounded existing tests, not an OS matrix.'
}
