const assert = require('node:assert/strict')
module.exports = async ({ app, win, html, read, until, waitFor, settle, click, key, frame, owner, store, snapshot, bytes, raw, runtime }) => {
  const id = 'tui-monitor', other = 'tui-output', trigger = '[data-toolkit-id="tui-monitor"]'
  const proof = raw.customization = { geometry: [], themes: [], restart: null }
  raw.boundary = 'Actual App, Editor, palette selector, icon picker, ToolkitPopover and TerminalView with private Native TUI. Real Renderer process replacement retains preferences and original Run; private local Core connector replaces Hosted Core. No installed app or upstream program claim.'
  const focus = async () => { app.focus({ steal: true }); win.moveTop(); win.focus(); win.webContents.focus(); await until('document.hasFocus()') }
  const open = async (tool = id) => {
    await click(`[data-toolkit-id="${tool}"]`)
    await until('!!document.querySelector(".toolkit-tui .xterm-screen") && !document.querySelector(".toolkit-tui .terminal-view__xterm--hydrating")')
  }
  const close = async () => { await click('.toolkit-tui [data-toolkit-close]'); await until('!document.querySelector(".performance-popover")') }
  const box = () => read(`(()=>{const n=document.querySelector('.performance-popover'),r=n.getBoundingClientRect();return{width:r.width,height:r.height,right:r.right,bottom:r.bottom,style:{width:n.style.width,height:n.style.height}}})()`)
  const pref = () => read(`window.tuiScene.preference('${id}')`)
  const palette = async (value) => {
    // Dispatch the native select's change through the real React consumer, leaving the open terminal in place.
    await read(`(()=>{const s=document.querySelector('[aria-label="Tool terminal palette"]');s.value=${JSON.stringify(value)};s.dispatchEvent(new Event('change',{bubbles:true}))})()`)
    await settle()
  }
  const color = () => read('getComputedStyle(document.querySelector(".toolkit-tui .terminal-view")).backgroundColor')
  await focus()
  await read('window.tuiScene.iconSheet()'); await settle(); await frame('icon-sizes-dark'); await read('window.tuiScene.closeIconSheet()')
  await waitFor(async () => (await snapshot(id)).state === 'running', 'Private TUI running before preferences change')
  const original = await snapshot(id), run = original.admission.run
  const nativeBefore = await (await runtime.toolkitRunPort()).status({ runId: run.runId })
  assert.ok(nativeBefore.pid > 0); assert.equal(nativeBefore.state, 'running')
  proof.original = { snapshot: original, native: nativeBefore }
  await click('.surface-navigation [aria-label="Settings"]')
  await until('!!document.querySelector("nav [data-settings-target=toolkit]")')
  await click('nav [data-settings-target="toolkit"]'); await click('[data-tool-id="tui-monitor"]')
  await until('window.tuiScene.editor().then(value=>value?.language==="shell")')
  await click('.toolkit-editor .monaco-editor')
  for (const type of ['keyDown', 'keyUp']) win.webContents.sendInputEvent({ type, keyCode: 'A', modifiers: ['meta'] })
  await key('Backspace')
  await until('window.tuiScene.editor().then(value=>value.value==="")')
  await click('.toolkit-editor__footer .primary-button')
  await waitFor(() => owner.current.toolkit.tools.find(tool => tool.id === id).script === '', 'Blank command saved through original owner')
  assert.equal((await store.get()).toolkit.tools.find(tool => tool.id === id).script, '')
  assert.deepEqual((await snapshot(id)).admission.run, run)
  await read('document.querySelector(".toolkit-editor__identity").scrollIntoView({block:"start"})')
  await click('.toolkit-icon-picker > summary')
  assert.equal(await read('document.querySelectorAll(".toolkit-icon-picker input[type=radio]").length'), 18)
  await frame('icons-dark')
  await click('[aria-label="Search tool icons"]'); await win.webContents.insertText('磁盘')
  await until('document.querySelectorAll(".toolkit-icon-picker input[type=radio]").length===1')
  assert.equal(await read('document.querySelector(".toolkit-icon-picker input[type=radio]").value'), 'hard-drive')
  await frame('icons-search')
  await click('.toolkit-icon-picker label:has(input[value="hard-drive"])'); await key('Escape')
  assert.equal(await read('document.activeElement===document.querySelector(".toolkit-icon-picker summary")'), true)
  await click('.toolkit-editor__footer .primary-button')
  await waitFor(() => owner.current.toolkit.tools.find(tool => tool.id === id).icon === 'hard-drive', 'Icon saved through original config owner')
  await until(`!!document.querySelector('${trigger} [data-semantic-icon="object.disk"]')`)
  await read('document.querySelector(".toolkit-editor__terminal-appearance").scrollIntoView({block:"center"})')
  await frame('palette-settings-dark')
  await open()
  const terminalNode = await read('window.originalToolkitTerminal=document.querySelector(".toolkit-tui .terminal-view__xterm");true')
  assert.equal(terminalNode, true)
  const attachment = raw.sessions.attachments.at(-1), count = raw.sessions.attachments.length
  proof.themes.push({ choice: 'global', color: await color() })
  await palette('nord')
  await until('getComputedStyle(document.querySelector(".toolkit-tui .terminal-view")).backgroundColor==="rgb(46, 52, 64)"')
  proof.themes.push({ choice: 'nord', color: await color() })
  assert.equal(await read('document.querySelector(".toolkit-tui .terminal-view__xterm")===window.originalToolkitTerminal'), true)
  assert.equal(raw.sessions.attachments.length, count)
  assert.equal(raw.sessions.attachments.at(-1).attachmentId, attachment.attachmentId)
  await frame('terminal-nord')
  await read('window.tuiScene.failPreferenceStorage(true)')
  await palette('dracula')
  await until('window.tuiScene.saveWarning()?.includes("Private preference storage unavailable")')
  assert.equal(await read('document.querySelector(".toolkit-tui .terminal-view__xterm")===window.originalToolkitTerminal'), true)
  assert.equal(raw.sessions.attachments.length, count)
  await click('.toolkit-tui .xterm-screen'); await key('Down')
  await waitFor(async () => (await bytes(run)).includes('Keyboard input received'), 'Storage failure preserves Native terminal input')
  await close()
  await click('.global-system-notices__trigger')
  await until('document.querySelector(".global-system-notices__details")?.matches(":popover-open")')
  assert.equal(await read('document.querySelector(".global-system-notices__details").textContent.includes("Saving the workbench is unconfirmed")'), true)
  await click('.notification-item:has(.notification-item__action[title^="Retry saving:"]) .notification-item__headline')
  await until('document.querySelector(".global-system-notices__details").textContent.includes("Private preference storage unavailable")')
  await frame('palette-save-service-window')
  await read('window.tuiScene.failPreferenceStorage(false)')
  await click('.global-system-notices__details .notification-item__action[title^="Retry saving:"]')
  await until('window.tuiScene.saveWarning()===null')
  proof.saveFailure = { originalWarningVisible: true, inputPreserved: true, originalRetryConverged: true }
  // The original center may close itself when its last warning converges.
  if (await read('!!document.querySelector(".global-system-notices__details")?.matches(":popover-open")'))
    await click('[aria-label="Collapse system notifications"]')
  await open(); await palette('nord')
  const initial = await box()
  win.webContents.debugger.attach('1.3')
  const start = await read('(()=>{const r=document.querySelector(".toolkit-popover-resize").getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()')
  await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mousePressed', ...start, button: 'left', clickCount: 1 })
  await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseMoved', x: start.x - 90, y: start.y - 60, buttons: 1, button: 'left' })
  await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseReleased', x: start.x - 90, y: start.y - 60, button: 'left', clickCount: 1 })
  win.webContents.debugger.detach(); await settle()
  const resized = await box(), preferred = await pref()
  assert.ok(resized.width > initial.width + 70 && resized.height > initial.height + 40)
  assert.ok(Math.abs(resized.right - initial.right) < 2 && Math.abs(resized.bottom - initial.bottom) < 2)
  assert.ok(Math.abs(preferred.size.width - resized.width) < 1 && Math.abs(preferred.size.height - resized.height) < 1)
  proof.geometry.push({ step: 'resize', initial, resized, preferred })
  await close(); await open()
  assert.deepEqual(await pref(), preferred)
  assert.equal((await box()).style.width, preferred.size.width + 'px')
  await frame('terminal-resized-reopened')
  win.setContentSize(680, 700); await until('innerWidth===680'); await settle()
  const clipped = await box()
  assert.ok(clipped.width <= 656 && clipped.height <= 676)
  assert.deepEqual(await pref(), preferred)
  proof.geometry.push({ step: 'narrow', clipped, preferred: await pref() })
  await frame('terminal-narrow')
  win.setContentSize(1440, 940); await until('innerWidth===1440'); await settle()
  assert.equal((await box()).style.width, preferred.size.width + 'px')
  await close(); await open(other)
  assert.notEqual((await box()).style.width, preferred.size.width + 'px')
  assert.equal(await read(`window.tuiScene.preference('${other}')??null`), null)
  await close(); await open()
  await palette('global')
  await owner.update(config => ({ ...config, appearance: { ...config.appearance, terminalTheme: 'solarized-light', appAppearance: 'light' } }))
  await until('document.documentElement.dataset.appearance==="light"')
  await until('getComputedStyle(document.querySelector(".toolkit-tui .terminal-view")).backgroundColor==="rgb(253, 246, 227)"')
  proof.themes.push({ choice: 'global-solarized-light', color: await color() })
  await frame('terminal-global-light')
  await close()
  await focus()
  await read('document.querySelector(".toolkit-editor__identity").scrollIntoView({block:"start"})')
  await click('.toolkit-icon-picker > summary'); await click('[aria-label="Search tool icons"]')
  await read(`(()=>{const input=document.querySelector('[aria-label="Search tool icons"]');input.focus();input.select()})()`)
  await key('Backspace'); await until('document.querySelectorAll(".toolkit-icon-picker input[type=radio]").length===18')
  await frame('icons-light')
  win.setContentSize(720, 860); await until('innerWidth===720'); await settle(); await frame('icons-light-narrow')
  await key('Escape')
  win.setContentSize(1440, 940); await until('innerWidth===1440'); await settle()
  await read('window.tuiScene.iconSheet()'); await settle(); await frame('icon-sizes-light'); await read('window.tuiScene.closeIconSheet()')
  await open()
  await palette('workspace')
  assert.equal((await pref()).theme, 'workspace')
  await frame('terminal-workspace-light')
  await palette('nord')
  await close()
  const beforePid = win.webContents.getOSProcessId(), beforeRestart = await pref()
  await win.webContents.session.flushStorageData()
  const crashed = new Promise(resolve => win.webContents.once('render-process-gone', (_event, details) => resolve(details)))
  win.webContents.forcefullyCrashRenderer(); await crashed
  await win.loadFile(html); await focus(); await until('window.tuiScene?.ready')
  assert.notEqual(win.webContents.getOSProcessId(), beforePid)
  assert.deepEqual(await pref(), beforeRestart)
  await open()
  assert.equal((await box()).style.width, preferred.size.width + 'px')
  assert.equal(await color(), 'rgb(46, 52, 64)')
  const current = await snapshot(id), nativeAfter = await (await runtime.toolkitRunPort()).status({ runId: run.runId })
  assert.deepEqual(current.admission.run, run)
  assert.equal(nativeAfter.pid, nativeBefore.pid)
  proof.restart = { beforePid, afterPid: win.webContents.getOSProcessId(), beforeRestart, restored: await pref(), originalRun: run, restoredRun: current.admission.run, originalNativePid: nativeBefore.pid, restoredNativePid: nativeAfter.pid }
  await click('.toolkit-tui .xterm-screen'); await key('Down')
  await waitFor(async () => (await (await runtime.toolkitRunPort()).status({ runId: run.runId })).acceptedInputBytes > nativeAfter.acceptedInputBytes, 'Restarted Renderer input reaches the original Native Run')
  await waitFor(async () => (await bytes(run)).includes('Keyboard input received'), 'Original Native TUI still consumes input after Renderer restart')
  await frame('terminal-restored')
}
