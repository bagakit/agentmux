const assert = require('node:assert/strict')

module.exports = async ({ win, panel, findButton, read, until, click, type, capture, theme }) => {
 const select = selector => 'js:' + panel + '.querySelector(' + JSON.stringify(selector) + ')'
 const named = label => 'js:' + findButton(label)
 const calls = method => read('window.moteNativeGroupsCapture.calls.filter(call=>call.method===' + JSON.stringify(method) + ')')
 await click(select('button[aria-label="创建群聊"]'))
 await type('.mote-group__field input', '群研究工作台')
 await click(select('.mote-group__candidate:first-child input'))
 await click(select('.mote-group__candidate:nth-child(2) input'))
 await click(select('.mote-group-settings__create summary'))
 await click(select('.mote-group-settings__face-pick:first-child'))
 await click(select('.mote-group-settings__face-pick:nth-child(2)'))
 await type('.mote-group-settings__create textarea', '请在群文件里保留结论的原始依据。')
 await read('(()=>{const node=document.querySelector(".mote-group-settings__create select"); const choice=[...node.options].find(option=>option.text==="群研究资料"); if(!choice) throw Error("Missing original Topic"); const set=Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,"value").set;set.call(node,choice.value);node.dispatchEvent(new Event("change",{bubbles:true}));})()')
 await capture('01-create-group-custom-avatar-dark')
 await click(named('创建群聊'))
 await until(panel + '.querySelector(".mote-group__header .mote-group-avatar")?.dataset.faces==="2"', 'Exact selected Mote avatars compose the committed group')
 const [created] = await calls('space.mote.group.create')
 assert.equal(created.input.avatarMoteIds.length, 2)
 assert.equal(created.input.announcement, '请在群文件里保留结论的原始依据。')
 assert.ok(created.input.topic?.zoneId, 'Creation must send the exact bound Topic')
 await click(select('button[aria-label="群研究工作台 · 群成员"]'))
 await until(panel + '.querySelector(".mote-group-settings")?.checkVisibility()', 'Original group settings open')
 await click(select('.mote-group-settings__member-actions button:first-child'))
 await until(panel + '.querySelector(".mote-group-settings__member")?.innerText.includes("管理员")', 'Member role updates in the group')
 await capture('02-group-management-members-dark')
 await click(select('.mote-group-settings__member:nth-child(2) .mote-group-settings__member-actions button:last-child'))
 await until(panel + '.querySelector(".mote-group-settings__member:nth-child(2)")?.innerText.includes("已移出")', 'Membership state retains its identity')
 await click(select('.mote-group-settings__invite summary'))
 await click(select('.mote-group-settings__invite input'))
 await click(named('邀请成员'))
 await until('window.moteNativeGroupsCapture.calls.some(call=>call.method==="space.mote.group.members.add")')
 await click(named('公告与设置'))
 await type('.mote-group-settings textarea', '更新后的群公告：每条结论带上来源。')
 await capture('03-group-announcement-editor-dark')
 await click(select('.mote-group-settings__face-pick:nth-child(2)'))
 await read('window.moteNativeGroupsCapture.conflictNextUpdate()')
 await click(named('保存群资料'))
 await until(panel + '.innerText.includes("可以把当前修改带到新版本再确认")', 'Definitive version conflict refreshes and retains the current edits')
 assert.equal(await read('document.querySelector(".mote-group-settings textarea").value'), '更新后的群公告：每条结论带上来源。')
 assert.ok(!(await read(panel + '.innerText.includes("核对原操作")')))
 await capture('07-group-version-conflict-dark')
 await click(named('按新版本继续编辑'))
 await click(named('保存群资料'))
 await until(panel + '.querySelector(".mote-group-settings__body > button")?.disabled', 'Original group settings receipt is confirmed')
 const updates = (await calls('space.mote.group.update')).filter(call => call.input.announcement)
 assert.equal(updates.length, 2, 'A new change only follows explicit confirmation')
 assert.equal(updates[1].input.expectedRevision, updates[0].input.expectedRevision + 1)
 assert.notEqual(updates[0].input.operationId, updates[1].input.operationId)
 assert.equal(updates[0].input.avatarMoteIds.length, 2)
 assert.equal(updates[1].input.avatarMoteIds, undefined, 'A removed member is excluded while the current avatar and announcement are kept')
 await click(named('群聊'))
 await until(panel + '.querySelector(".mote-group__timeline")?.innerText.includes("每条结论带上来源")', 'A structured system publication appears in the original group')
 win.setContentSize(720, 700)
 await theme(true)
 await capture('04-group-announcement-public-narrow-light')
 await click(named('群文件'))
 await until(panel + '.innerText.includes("研究记录.md")', 'Bound original Topic files are listed')
 await capture('05-group-files-narrow-light')
 await click(named('研究记录.md'))
 await until(panel + '.innerText.includes("这一份资料来自群绑定的原 Topic")', 'Original Topic file opens through the File owner')
 await capture('06-group-file-readable-narrow-light')
 await click(named('返回群聊'))
 await until(panel + '.querySelector(".mote-group__header h2")?.textContent==="群研究工作台"', 'Returning retains the original group')
}
