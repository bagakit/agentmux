const assert = require('node:assert/strict')
const { nativeRendererInput } = require('../settings-connections/native-input.cjs')
module.exports = async ({ win, result, panel, findButton, read, until, click, capture, settle }) => {
  const { type } = nativeRendererInput(win, result.interactions, '')
  const editor = await read(`(()=>{const e=${panel}.querySelector('[contenteditable=true]');window.threadDiscoveryEditor=e;return e?.textContent})()`)
  await click('js:' + panel + '.querySelector(".mote-conversation__related > summary")')
  await until(panel + '.querySelector(".mote-conversation__related")?.innerText.includes("补齐 Mote 的产品体验")', 'Exact related work source')
  await capture('12-main-related-threads-wide-dark')
  await click('js:' + panel + '.querySelector(".mote-conversation__related .mote-work-event__summary")')
  await until(panel + '.querySelector(".mote-conversation__related")?.innerText.includes("主对话和 Threads 已分开")', 'Exact original work reply inline')
  await capture('13-main-inline-work-expanded-wide-dark')
  await click('js:' + findButton('查看全部 Threads'))
  await until(panel + '.querySelector(".mote-threads-panel:not([hidden]) .mote-threads__search input")', 'Same Threads discovery consumer')
  const input = '[data-pmo-teams-topic-floating]:popover-open .mote-threads__search input'
  await type(input, '产品体验')
  await until(panel + '.querySelector(".mote-threads__list > li:not([hidden])")?.innerText.includes("产品体验")')
  win.setContentSize(760, 720); await read('window.moteDiscussionCapture.theme(true)'); await settle()
  await capture('14-threads-search-narrow-light')
  await type(input, '没有匹配的标题')
  await until(panel + '.innerText.includes("没有匹配的已载入工作")')
  await capture('15-threads-no-match-narrow-light')
  await type(input, '')
  await click('js:' + findButton('Discussion'))
  assert.equal(await read(panel + '.querySelector("[contenteditable=true]")===window.threadDiscoveryEditor && window.threadDiscoveryEditor.isConnected'), true, 'Original Main editor retained through discovery')
  assert.equal(await read('window.threadDiscoveryEditor.textContent'), editor)
  await click('js:' + panel + '.querySelector(".mote-conversation__related > summary")')
  win.setContentSize(1180, 850); await read('window.moteDiscussionCapture.theme(false)'); await settle()
  result.operations.push({ name: 'thread-discovery-retains-main', editor, inputBoundary: 'Only search fields were edited; no Composer send or Agent operation.' })
}
