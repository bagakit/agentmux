const assert = require('node:assert/strict')

module.exports = async ({ win, panel, findButton, read, until, click, type, capture, theme }) => {
 const rail = label => 'js:' + panel + '.querySelector(' + JSON.stringify('button[aria-label="' + label + '"]') + ')'
 const named = label => 'js:' + findButton(label)
 await until(panel + '.innerText.includes("协作体验研究")', 'Native group drives actual IM rail')
 await click(rail('协作体验研究'))
 await until(panel + '.querySelector(".mote-group__timeline")?.innerText.includes("第一次找到群聊")', 'Canonical timeline opens from the rail')
 assert.equal(await read(panel + '.querySelector(".mote-group__message[data-own] strong").textContent'), '我')
 await capture('01-group-public-wide-dark')
 await click(rail('协作体验研究 · 群成员'))
 await until(panel + '.querySelector(".mote-group__members")?.checkVisibility()', 'Group avatar opens membership')
 await capture('02-group-members-wide-dark')
 await click(named('研究搭档'))
 await until(panel + '.innerText.includes("正在查看 研究搭档 的群内视角")', 'Mote perspective opens on the same group')
 assert.equal(await read(panel + '.querySelector(".mote-group__timeline").innerText.includes("先用这条路径")'), false)
 assert.equal(await read(panel + '.querySelector(".mote-group__timeline").innerText.includes("第一次找到群聊")'), true)
 assert.equal(await read(panel + '.querySelector(".mote-group__composer")'), null)
 await capture('03-group-member-perspective-wide-dark')
 await click('js:' + panel + '.querySelector(".mote-group__thread summary")')
 await until(panel + '.querySelector("[data-mote-session-conversation]")?.checkVisibility()', 'The original dedicated Session work is readable')
 await capture('04-group-original-work-wide-dark')
 await click(named('群聊原文'))
 assert.equal(await read('document.activeElement.dataset.groupMessageId'), 'public-reply', 'Mote perspective links to the exact canonical public reply')
 await click('js:' + panel + '.querySelector(".mote-group__recipients button")')
 await type('textarea[aria-label="群消息"]', '请核对这条消息只发布一次。')
 await click(named('发送'))
 await until(panel + '.innerText.includes("首次确认响应中断")', 'Exact original operation remains visible after a lost acknowledgement')
 await capture('05-group-unknown-send-wide-dark')
 await click(named('确认发送'))
 await until(panel + '.querySelector(".mote-group__composer textarea").value === ""', 'Clears only after recovering the same receipt')
 const sends = await read('window.moteNativeGroupsCapture.calls.filter(call=>call.method==="space.mote.group.send")')
 assert.equal(sends.length, 2); assert.deepEqual(sends[0].input, sends[1].input)
 win.setContentSize(720, 700); await theme(true)
 await capture('06-group-public-narrow-light')
 await click(rail('创建群聊'))
 await until(panel + '.querySelector(".mote-group__create")?.checkVisibility()', 'Actual create entry in IM rail')
 await type('.mote-group__field input', '第二个独立群')
 const firstMember = 'js:' + panel + '.querySelector(".mote-group__candidate input")'
 await until(panel + '.querySelector(".mote-group__candidate input")?.checkVisibility()', 'Confirmed eligible Mote can be selected')
 await click(firstMember)
 await capture('07-group-create-narrow-light')
 await click(named('创建群聊'))
 await until(panel + '.querySelector(".mote-group__header h2")?.textContent==="第二个独立群"', 'Fresh group opens with a separate identity')
 const creations = await read('window.moteNativeGroupsCapture.calls.filter(call=>call.method==="space.mote.group.create")')
 assert.equal(creations.length, 1)
 assert.equal(creations[0].input.members.length, 1)
 await click(named('返回'))
 await until(panel + '.innerText.includes("把协作体验补完整")', 'Returns to retained original Mote conversation')
 await click('js:' + panel + '.querySelector(' + JSON.stringify('[aria-label="工作"]') + ')')
 await until(panel + '.querySelector(".mote-thread-groups summary")?.checkVisibility()', 'Original Mote Threads discovers its groups')
 await click('js:' + panel + '.querySelector(".mote-thread-groups summary")')
 await click('js:' + panel + '.querySelector(".mote-thread-groups__row:last-of-type")')
 await until(panel + '.innerText.includes("正在查看 研究搭档 的群内视角")', 'Mote Threads leads straight to the exact group perspective')
}
