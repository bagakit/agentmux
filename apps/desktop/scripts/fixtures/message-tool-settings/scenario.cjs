const assert = require('node:assert/strict')

exports.run = async ({ read, q, until, settle, click, field, type, scene, capture, owner, result }) => {
  async function section(id) {
    const nav = q(`nav[aria-label="Settings sections"] [data-settings-target="${id}"]`)
    const title = await read(`${nav}?.textContent.trim()`)
    assert.ok(title, 'Read the actual registered section title before navigating')
    if (await read(nav + '.checkVisibility()')) await click(nav)
    else {
      await click(q('.settings-section-picker'))
      await until('!!document.querySelector(".settings-section-menu[role=menu]")')
      await click(`[...document.querySelectorAll('.settings-section-menu [role=menuitemradio]')].find(n=>n.textContent.trim()===${JSON.stringify(title)})`)
    }
    await until(`document.querySelector('.settings-page')?.dataset.settingsPage===${JSON.stringify(id)}`)
    await settle()
  }
  const inPane = (id, selector) => q(`[data-settings-pane="${id}"] ${selector}`)
  const save = (id, selector = '[data-settings-save-bar] button') => click(inPane(id, selector))
  const saved = (id, selector = '[data-settings-save-bar]') => until(`${inPane(id, selector)}?.textContent.includes('Changes saved')`)
  async function position(id, selector) {
    await read(`${inPane(id, selector)}.scrollIntoView({block:'start',behavior:'instant'})`)
    await settle()
  }
  const originals = structuredClone(owner.current.composerShortcuts)
  await type(field('Prompt'), 'Unsaved original Prompt retained across all five modules')
  await read(`window.messageToolPromptNode=${field('Prompt')}`)
  await section('message-tool')
  assert.equal(await read('document.querySelector(".settings-content__header h2").textContent'), 'User Input')
  const declared = await read('window.promptsProbe.shortcuts().bindings.filter(binding=>binding.scope==="message-tool")')
  assert.ok(declared.length > 0)
  const rows = await read(`(()=>{const pane=document.querySelector('[data-settings-pane="message-tool"]');return [...pane.querySelectorAll('[data-binding-id]')].map(n=>({id:n.dataset.bindingId,keys:[...n.querySelectorAll('kbd')].map(k=>k.textContent)}))})()`)
  assert.deepEqual(rows.map(row => row.id), declared.map(binding => binding.id))
  for (const row of rows) assert.deepEqual(row.keys, declared.find(binding => binding.id === row.id).keys)
  assert.equal(await read(`${inPane('message-tool', '[aria-label="Mailbox"]')}===null`), true)
  await click(inPane('message-tool', 'input[value="two-line"]'))
  await section('a2a'); await section('automation'); await section('amux-protocols'); await section('message-tool')
  assert.equal(await read(`${inPane('message-tool', 'input[value="two-line"]')}.checked`), true)
  await save('message-tool'); await saved('message-tool')
  assert.equal(owner.current.messageToolInitialLayout, 'two-line')
  assert.deepEqual(owner.current.composerShortcuts, originals)

  await section('automation')
  await click(inPane('automation', '[aria-label="Continue interrupted work after recovery"]'))
  await save('automation'); await saved('automation')
  assert.equal(owner.current.continuity.continuationEnabled, false)
  await type(inPane('automation', '[aria-label="Default progress interval"]'), '45')
  await type(inPane('automation', '[aria-label="Default progress prompt"]'), 'Review the original acceptance criteria and report the next useful step.')
  await type(inPane('automation', '[aria-label="Default arrangement timezone"]'), 'America/Argentina/Buenos_Aires')
  const defaultSave = '[data-settings-save-bar] button'
  await click(`[...document.querySelectorAll('[data-settings-pane="automation"] ${defaultSave}')].find(n=>n.textContent==='Save task defaults')`)
  await until(`${inPane('automation', '[aria-label="Default progress interval"]')}.value==='45' && ![...document.querySelectorAll('[data-settings-pane="automation"] [data-settings-save-bar] button')].some(n=>n.textContent==='Save task defaults'&&!n.disabled)`)
  assert.equal(owner.current.automation.progressIntervalMs, 45 * 60_000)
  assert.equal(owner.current.automation.calendarTimezone, 'America/Argentina/Buenos_Aires')
  assert.equal(owner.current.continuity.continuationEnabled, false)
  await section('continuity')
  assert.equal(await read(`${inPane('continuity', '[data-continuity-interruption-settings]')}===null`), true)
  await type(inPane('continuity', '[aria-label="Recovery wait"]'), '2.125')
  await save('continuity'); await saved('continuity')
  assert.equal(owner.current.continuity.activeRecoveryDelayMs, 2125)
  assert.equal(owner.current.continuity.continuationEnabled, false)

  await section('a2a')
  await click(inPane('a2a', 'input[value="silent"]')); await save('a2a'); await saved('a2a')
  assert.equal(owner.current.a2a.notifications, 'silent')
  await click(inPane('a2a', 'input[value="notify"]'))
  await owner.update(current => ({ ...current, a2a: { ...current.a2a, notifications: 'follow-global' } }))
  await save('a2a')
  await until(`${inPane('a2a', '[role="alert"]')}?.textContent.includes('changed since')`)
  assert.equal(await read(`${inPane('a2a', 'input[value="notify"]')}.checked`), true)
  await capture('1480-dark-a2a-conflict.png', 'Original ConfigOwner conflict keeps the edited A2A preference and a reachable retry')
  await owner.update(current => ({ ...current, a2a: { ...current.a2a, notifications: 'silent' } }))
  await save('a2a'); await saved('a2a')
  assert.equal(owner.current.a2a.notifications, 'notify')

  for (const [width, appearance] of [[1480, 'dark'], [640, 'light'], [320, 'dark'], [320, 'light']]) {
    await scene(width, appearance)
    await section('message-tool')
    await position('message-tool', '[data-message-tool-settings]')
    await capture(`${width}-${appearance}-input.png`, 'User Input: original layout and configurable shortcut input')
    await position('message-tool', '[data-settings-field="message-shortcuts"]')
    await capture(`${width}-${appearance}-keys.png`, 'Original shared keyboard manual remains readable and separate from editable prefixes')
    await section('a2a')
    await position('a2a', '[data-a2a-settings]')
    await capture(`${width}-${appearance}-a2a.png`, 'A2A user banners are separate from Agent reference notifications')
    await section('automation')
    await position('automation', '[data-continuity-interruption-settings]')
    await capture(`${width}-${appearance}-continuation.png`, 'Recovery continuation and unsupported-only active fallback are independently saved')
    await position('automation', '[data-settings-field="progressIntervalMs"]')
    await capture(`${width}-${appearance}-task-defaults.png`, 'Saved new-task progress defaults and explicit arrangement timezone')
    await position('automation', '[data-settings-field="checkInQuietStart"]')
    await capture(`${width}-${appearance}-quiet-defaults.png`, 'Quiet follow-up defaults have units and explicit per-arrangement opt-in')
    if (width === 1480 || (width === 320 && appearance === 'light')) {
      await section('prompts')
      assert.equal(await read(`(${field('Prompt')})===window.messageToolPromptNode`), true)
      assert.equal(await read(`(${field('Prompt')}).value`), 'Unsaved original Prompt retained across all five modules')
      await capture(`${width}-${appearance}-prompts.png`, 'Original Prompt resource editor retains its same dirty node and library')
      await section('amux-protocols')
      assert.equal(await read(`${inPane('amux-protocols', '[data-settings-save-bar]')}===null`), true)
      await capture(`${width}-${appearance}-protocols.png`, 'amux Protocols remains a separate readonly reference')
      await section('continuity')
      await position('continuity', '.continuity-settings')
      await capture(`${width}-${appearance}-execution.png`, 'Execution retains native recovery controls without duplicated continuation settings')
    }
  }
  await scene(1480, 'dark'); await section('overview')
  const ids = await read(`[...document.querySelectorAll('[aria-labelledby="settings-overview-message-tool"] [data-settings-section]')].map(n=>n.dataset.settingsSection)`)
  assert.deepEqual(ids, ['message-tool', 'a2a', 'automation', 'prompts', 'amux-protocols'])
  await read(`document.querySelector('[aria-labelledby="settings-overview-message-tool"]').scrollIntoView({block:'center',behavior:'instant'})`)
  await capture('1480-dark-overview.png', 'All five independent Message Tool entries derive from the original module catalog')
  result.messageTool = { bindings: declared, ids, layout: owner.current.messageToolInitialLayout, promptDraftRetained: true, defaults: owner.current.automation, a2a: owner.current.a2a, continuation: owner.current.continuity }
}
