const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { app, BrowserWindow } = require('electron')
const { nativeRendererInput } = require('../settings-connections/native-input.cjs')
const [html, privateRoot, evidence] = process.argv.slice(2)
app.setPath('userData', path.join(privateRoot, 'user-data')); app.setPath('sessionData', path.join(privateRoot, 'session-data'))
const result = { passed: false, frames: [], interactions: [], boundary: 'Production Workbench/Agent header/dialog/Settings and CSS; controlled public application/group/binding DTOs only. Real IPC/native SDK/binding and actual App route are proven separately. No live account, native permission or installation claim.' }
let win
app.whenReady().then(async () => {
  try {
    win = new BrowserWindow({ width: 1380, height: 980, show: false, webPreferences: { contextIsolation: true, nodeIntegration: false, sandbox: true, backgroundThrottling: false } })
    await win.loadFile(html)
    const { read, until, settle, click } = nativeRendererInput(win, result.interactions, '')
    await until('window.channelEntryProof?.ready && document.querySelector("[data-channel-entry=discord]")')
    await read('window.__connectionsTrustedEvents=[];for(const type of ["click","keydown","input"])document.addEventListener(type,event=>window.__connectionsTrustedEvents.push({type,trusted:event.isTrusted,key:event.key}),true)')
    win.showInactive(); win.focus(); win.webContents.focus(); await until('document.hasFocus()')
    const node = selector => 'document.querySelector(' + JSON.stringify(selector) + ')'
    const text = (label, selector = '[role="dialog"] button') => 'js:[...document.querySelectorAll(' + JSON.stringify(selector) + ')].find(node=>node.textContent.trim()===' + JSON.stringify(label) + ')'
    async function capture(name) { await settle(); const file = name + '.png'; fs.writeFileSync(path.join(evidence, file), (await win.webContents.capturePage()).toPNG()); result.frames.push(file) }
    await click('[data-channel-entry=discord]'); await until('document.querySelector(".connector-header-menu")')
    await capture('channel-unbound-menu-wide')
    await click(text('Connect a group', '.connector-header-menu [role="menuitem"]'))
    await until(node('[aria-label="Existing group"]') + ' && ' + node('[aria-label="New group"]') + '?.disabled')
    await click('.selection-field[aria-label="Existing group"]')
    await click('[role="menuitemradio"][data-value="345678901234567890"]')
    await until('document.querySelector(".agent-connector-room-overview")?.textContent.includes("research-and-engineering")')
    await capture('channel-existing-wide')
    win.setContentSize(520, 980); await until('innerWidth===520'); await capture('channel-existing-narrow')
    await click('js:[...document.querySelectorAll(".agent-connector-check input")].find(node=>node.closest("label").textContent.includes("Share new"))')
    await click(text('Connect group'))
    await until(node('[aria-label="Group connection status"]'))
    await click('[aria-label="Close group setup"]')
    win.setContentSize(1380, 980); await until('innerWidth===1380')
    await until('document.querySelector("[data-channel-entry=discord]")?.getAttribute("aria-label").includes("Discord") && document.querySelector("[data-channel-entry=discord]")?.dataset.channelState!=="unbound"')
    await click('[data-channel-entry=discord]'); await until('document.querySelector(".connector-header-menu__item")')
    await capture('channel-bound-menu-wide')
    win.setContentSize(520, 980); await until('innerWidth===520');
    if (!await read('document.querySelector(".connector-header-menu__item")')) await click('[data-channel-entry=discord]')
    await until('document.querySelector(".connector-header-menu__item")'); await capture('channel-bound-menu-narrow')
    await click('.connector-header-menu__item')
    await until(node('[aria-label="Group connection status"]'))
    win.setContentSize(1380, 980); await until('innerWidth===1380'); await capture('channel-details-wide')
    await click('js:[...document.querySelectorAll("[role=dialog] details>summary")].find(node=>node.textContent.trim()==="Connection details")')
    await read('window.channelEntryProof.omitOriginal=true')
    await click(text('Application settings'))
    await until('document.querySelector("[data-channel-target-issue]")')
    await capture('channel-target-unconfirmed-wide')
    await read('window.channelEntryProof.omitOriginal=false')
    await click('[data-settings-pane=discord] [data-channel-target-issue] button')
    await until('document.querySelector("[data-settings-pane=discord] [data-connection-check]")')
    await capture('channel-exact-settings-wide')
    const facts = await read('({calls:window.channelEntryProof.calls,errors:window.channelEntryProof.errors,text:document.querySelector("[data-settings-pane=discord]")?.textContent})')
    assert.deepEqual(facts.errors, []); assert.equal(facts.calls.filter(method => method === 'connection.bind').length, 1)
    assert.equal(facts.calls.includes('connection.room.create'), false); assert.equal(facts.calls.includes('connection.grant'), false)
    assert.equal(facts.text.includes('123456789012345678'), true)
    result.facts = facts; result.passed = true
  } catch (error) { result.failure = { name: error.name, message: error.message, stack: error.stack }; if (win && !win.isDestroyed()) fs.writeFileSync(path.join(evidence, 'failure.png'), (await win.webContents.capturePage()).toPNG()) }
  finally { fs.writeFileSync(path.join(evidence, 'render.json'), JSON.stringify(result, null, 2)); win?.destroy(); app.exit(result.passed ? 0 : 1) }
})
