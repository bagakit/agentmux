/**
 * 「这个身份画成什么颜色」——把一个说话人 id 确定性地映射到一个色相。
 *
 * 说话人是**开放集**（A2A 落地后同一条对话里会有多个 Agent，见对话交互合同「对话体的说话人要有
 * 头像与身份」）。开放集意味着**不能**用一张固定的调色板：token 里只有 green/blue/amber 这几个语义
 * 强调色，把它们轮流发给 N 个 Agent 会在第四个身份上撞色。所以身份色由 id 派生——但只派生**色相**
 * 一个维度，饱和度与明度固定在 token 强调色所在的柔和带里（见 conversation-avatar.css），于是任意
 * 色相都与深色主题和谐、不会刺出去。这就是「颜色从 token 系统里来」对开放集的正确读法：不选颜色，
 * 选一条与 token 同调的生成带。
 *
 * 三条硬性质，都被测试钉住：
 * - **确定性**：同一 id 任意次调用得同一个数。身份的颜色不能随渲染次数或顺序变——那正是设计
 *   明确禁止的「按渲染顺序取色」。
 * - **纯**：只吃 id 字符串，不读时钟、不读随机源、不读 DOM。可在无 DOM 的测试里直接求值。
 * - **区分度**：相邻的 id（`agent-1` / `agent-2`）必须散到色相环上离得开的两处，而不是差一度。
 *   朴素的字符和（djb2）会让相邻串只差一两度，肉眼分不开；这里用 FNV-1a 逐字节混合后再乘一个
 *   32-bit 黄金比常数做 avalanche，让输入的一个字节之差扩散到整个输出。
 */

/**
 * 语义色占用的色相，以及各自要让开的半宽（度）。
 *
 * 实测自 tokens.css：`--red` 1.9°、`--amber` 40.2°、`--green` 143.0°、`--blue` 213.8°。这四个不是
 * 「好看的颜色」而是**状态词汇**：amber 专表「需要你」、red 表失败、green 表成功、blue 表人类说话人
 * （`.conversation-avatar--human` 就取 `--blue`）。一个落在 40° 的身份色会被读成「这个 Agent 在等你」，
 * 而它其实只是名字散列到了那里——身份色误报状态，比撞色难查得多。
 *
 * 这正是同一套推理在人类身份上已经用过一次的结论：人类不派生色相、固定取 `--blue`，因为「派生结果
 * 可能撞到语义色」。那条论证对 agent 一样成立，所以这里把它兑现成代码，而不是只写在人类那条注释里。
 *
 * 半宽 22° 略大于「可分辨」所需的 20°：让开的目的不是恰好不等于，而是不会被**误读成**那个状态。
 */
const RESERVED_HUES = [1.9, 40.2, 143, 213.8] as const
const RESERVED_HALF_WIDTH = 22

/**
 * 一个色相是否让开了所有语义色。
 *
 * 导出的是**规则**而不是保留色表：CSS 里那个兜底色相（`--speaker-hue` 的声明值）必须遵守同一条
 * 规则，而两个该联动的常量分居两文件必然漂移——曾经真的漂过，CSS 兜底写着 145，离 green 只有 2°，
 * 正落在这个派生函数存在要避开的那片弧里。所以让测试拿这个谓词去问那个声明值，而不是在测试里
 * 手抄一份保留色表（那只是把同一份数据抄到了第三个地方）。
 */
export function clearsSemanticHues(hue: number): boolean {
  return RESERVED_HUES.every((reserved) => {
    const delta = Math.abs(hue - reserved)
    // 环上距离：red 在 1.9°，359° 离它只有 2.9° 而不是 357.1°。
    return Math.min(delta, 360 - delta) >= RESERVED_HALF_WIDTH
  })
}

/**
 * 允许的色相区间（整数度，闭区间），从保留弧的补集算出来，按起点升序。
 *
 * 实测得到三条：`[63,121] [165,191] [236,339]`。**三条而不是四条**——red 在 1.9°、amber 在 40.2°，
 * 相距 38.3° 小于两倍半宽，两段禁区连成一整片暖色。下一个人会想把半宽调小来"省回"这一片，但那恰好
 * 会在 red 与 amber 之间劈出一条窄缝，缝里的身份同时离两个状态色都只有 20° 出头——比一片宽禁区更糟。
 *
 * 用区间表而不是「算出色相再往外推」：后者会把保留弧两侧的值都挤到弧的边缘上，制造出人为的聚簇——
 * 恰好破坏这个函数存在的理由（相邻 id 要散得开）。而且 red 的弧跨过 0°，「往外推」在那一段会直接算错
 * （实测过：10.8% 的身份仍落在 red 附近）。所以先把补集摊平成若干条区间，再把散列值当作这些区间拼起来
 * 的那条线段上的坐标——每条区间被取到的概率正比于它的长度，分布因此保持均匀（实测最差桶偏差 3.8%）。
 *
 * 逐度扫一圈而不是对端点排序：跨零那段不需要任何特例，而 360 次谓词调用是模块初始化时的一次性开销。
 */
const ALLOWED_HUES: readonly number[] = Array.from({ length: 360 }, (_, hue) => hue).filter(clearsSemanticHues)

/**
 * 把身份 id 映射到一个色相（整数度），避开语义色所在的那几段弧。纯函数。
 *
 * 只暴露色相：饱和度/明度由 CSS 固定在 token 带内，因此「颜色 = f(id)」在固定 S/L 下成立，而色相
 * 是唯一随身份变化的量，也是唯一需要跨 IPC/渲染稳定的量。整数度：色相的可分辨粒度远粗于 1°，给它
 * 小数位只会让 CSS 自定义属性变长，换不到任何一双眼睛能看见的东西。
 */
export function speakerColorHue(id: string): number {
  // FNV-1a：逐字节把 id 混进一个 32-bit 累加器。比字符和好在「顺序敏感」且扩散更均匀。
  let hash = 0x811c9dc5 // FNV offset basis
  for (let i = 0; i < id.length; i += 1) {
    hash ^= id.charCodeAt(i)
    // FNV prime 0x01000193；Math.imul 做 32-bit 有符号乘法，>>> 0 归一回无符号。
    hash = Math.imul(hash, 0x01000193) >>> 0
  }
  // avalanche：再乘 2^32 的黄金比共轭。它把 hash 里相邻的取值推散到值域各处，于是 `agent-1`
  // 与 `agent-2` 这种只差一个字节的 id 不会落在相邻色相上——「不同 id 要能区分」靠的就是这一步。
  const mixed = Math.imul(hash, 0x9e3779b1) >>> 0
  return ALLOWED_HUES[mixed % ALLOWED_HUES.length]!
}
