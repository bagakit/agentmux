/**
 * 扇出分支名的 slug —— 全仓唯一一处把任意文本变成合法名字的地方。
 *
 * 一个扇出分支名在走到计划之前会被 slug 两次：surface 侧先从 prompt 派生一个 stem，好在界面上就地
 * 拒绝一个不可用的名字；main 侧作为真正的权威，对 `baseName` 再 slug 一次并据此创建分支。两处都必须
 * 归一，但**不许各自记一份「合法分支名长什么样」**。
 *
 * 此前就是两份，而且并不完全一样：surface 那份在 `.slice(0, 40)` 之后多清一次尾部连字符（截断可能
 * 正好切在连字符上），main 那份没有。于是整条链的正确性挂在一个从未被写出来的不动点上——
 * `slug(surfaceStem(x)) === surfaceStem(x)`——它今天成立只是因为两份实现恰好对当下的输入一致，而且
 * 没有任何测试断言它。把不动点删掉的办法不是抽取加断言，而是只留一个函数：同一件事就退化成单函数的
 * 幂等性 `slug(slug(x)) === slug(x)`——那是单个函数自己的保证，再也不可能与第二份副本漂移。
 *
 * 所以这里是唯一的定义。任何执行面——surface 与权威一视同仁——都 import 它；新的面不许再手写一份
 * 自己的 lowercase / replace 链。
 */

// git refname 禁止很多东西；与其把 refname 的全部规则编码进来，不如收敛到一套保守字母表，它作为目录名
// 也无歧义——因为分支名同时会成为 worktree 的目录名。
//
// 末尾这次 `.replace(/-+$/gu, '')` 落在 40 字符截断**之后**，是承重的、不是装饰：截断可能正好切在连字符
// 上（"a-b-…-c-"），而一个以连字符结尾的分支名/目录名正是那份较松的副本会发出去的丑陋（有时非法）的
// 情形。也正是这次「截断后再清尾」让这个函数成为幂等。
export function fanOutSlug(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/gu, '-')
    .replace(/^-+|-+$/gu, '')
    .slice(0, 40)
    .replace(/-+$/gu, '')
}
