const assert = require('node:assert/strict')

/** Actual MobileApp/editor/Device owner; only original SDK read latency is controlled. */
module.exports = async ({ win, read, until, resize, tap, button, capture, result, phase }) => {
  const selector = '.mobile-mote-composer [contenteditable=true]'
  const body = '想把这个想法做成一个小实验，保留原始资料，也留下还没决定的部分。'
  const insertion = '先做一步，'
  const expected = body.slice(0, 5) + insertion + body.slice(5)
  const text = () => read(`document.querySelector(${JSON.stringify(selector)})?.textContent`)
  const observed = () => read(`(()=>{const e=document.querySelector(${JSON.stringify(selector)}),s=getComputedStyle(e);return {same:e===window.originalCaptureEditor,text:e.textContent,rect:e.getBoundingClientRect().toJSON(),fontSize:s.fontSize,lineHeight:s.lineHeight,selection:window.getSelection()?.anchorOffset,focused:document.activeElement===e}})()`)
  const saved = () => read('(()=>{const r=mobileProductScene.facts().record,c=r.conversation,p=c.moteTextSources?.[0];return {recordId:r.recordId,sid:r.selectedSessionId,address:p,body:p?new Map(c.drafts).get(p[1]):null,sessionB:new Map(c.drafts).get(JSON.stringify(["draft","session-mote"])),route:r.presentation?.moteView}})()')
  await until(`!!document.querySelector(${JSON.stringify(selector)})`)
  if (phase === 'restore') {
    await until(`document.querySelector(${JSON.stringify(selector)})?.textContent===${JSON.stringify(expected)}`)
    const original = await saved()
    assert.equal(original.body, expected)
    assert.equal(original.sessionB, '原 Session B 草稿，独立保留。')
    assert.equal(original.sid, 'session-mote')
    assert.equal(original.route.directAgent, false)
    assert.ok(original.address?.[1]?.includes('mote-main-start'))
    assert.equal(await read('mobileProductScene.facts().calls.filter(c=>["agent.open","sdk.submitAgentPrompt","space.mote.dialogue.input.submit"].includes(c.method)).length'), 0)
    await resize(390, 844); await read('mobileProductScene.setAppearance("light")')
    await capture('08-mobile-original-drafts-after-process-restart')
    result.operations.push({ action: 'original-device-address-and-both-drafts-restored', ...original })
    return
  }
  await resize(390, 844); await read('mobileProductScene.setAppearance("light")')
  await tap(selector, 'Write while the original Mote role read is pending', { scroll: false })
  await win.webContents.insertText(body)
  await until(`document.querySelector(${JSON.stringify(selector)})?.textContent===${JSON.stringify(body)}`)
  await read(`(()=>{const e=document.querySelector(${JSON.stringify(selector)}),r=document.createRange();window.originalCaptureEditor=e;e.focus();r.setStart(e.querySelector('p').firstChild,5);r.collapse(true);const s=window.getSelection();s.removeAllRanges();s.addRange(r);document.dispatchEvent(new Event('selectionchange'))})()`)
  const before = await observed()
  await capture('01-mobile-typing-during-original-read-390-light')
  await read('mobileProductScene.releaseComposerReads()')
  await capture('02-mobile-original-read-release-intermediate', { motion: true })
  await until('document.querySelector(".mobile-mote-composer .composer__editor")?.dataset.placeholder==="发消息"')
  const after = await observed()
  assert.equal(after.same, true); assert.equal(after.text, body); assert.equal(after.selection, 5)
  assert.equal(after.fontSize, before.fontSize); assert.equal(after.lineHeight, before.lineHeight)
  assert.equal(after.rect.x, before.rect.x); assert.equal(after.rect.width, before.rect.width)
  assert.equal(after.rect.y, before.rect.y); assert.equal(after.rect.height, before.rect.height)
  result.operations.push({ action: 'same-editor-original-read-transition', before, after })
  await win.webContents.insertText(insertion)
  await until(`document.querySelector(${JSON.stringify(selector)})?.textContent===${JSON.stringify(expected)}`)
  await until('mobileProductScene.facts().record.conversation.moteTextSources?.length===1')
  await capture('03-mobile-continue-middle-text-main-390-light')
  const main = await observed()
  await button('当前对话操作'); await button('新一轮', '.mobile-sheet')
  await until('document.querySelector(".mote-start")?.dataset.mode==="new"')
  assert.equal((await observed()).same, true)
  assert.equal(await text(), expected)
  await resize(320, 760); await read('mobileProductScene.setAppearance("dark")')
  await capture('04-mobile-same-draft-welcome-320-dark')
  await resize(390, 844); await read('mobileProductScene.setAppearance("light")')
  await tap('.mobile-mote-start-details > summary', 'Open the original Main reference')
  await read(`(()=>{window.mobileComposerAnimations=[];window.mobileComposerMotionListener=event=>{if(event.animationName!=='mobile-mote-body-enter')return;for(const animation of event.target.getAnimations()){if(animation.animationName!==event.animationName)continue;animation.pause();animation.currentTime=Number(animation.effect.getTiming().duration)/2;window.mobileComposerAnimations.push(animation)}};document.addEventListener('animationstart',window.mobileComposerMotionListener)})()`)
  await button('打开主对话', '.mobile-mote-start-details')
  await until('window.mobileComposerAnimations.length>0')
  const midpoint = await read('mobileComposerAnimations.map(animation=>({name:animation.animationName,duration:animation.effect.getTiming().duration,progress:animation.effect.getComputedTiming().progress,state:animation.playState}))')
  assert.ok(midpoint.every(value => value.duration > 0 && value.progress > 0 && value.progress < 1 && value.state === 'paused'))
  await capture('05-mobile-welcome-main-intermediate', { motion: true })
  await read('document.removeEventListener("animationstart",mobileComposerMotionListener);mobileComposerAnimations.forEach(animation=>animation.play())')
  result.operations.push({ action: 'original-body-animation-midpoint', midpoint, editor: await observed() })
  await until('!document.querySelector(".mote-start")&&document.querySelector(".mobile-conversation-slot:not([hidden])")')
  assert.equal((await observed()).same, true); assert.equal(await text(), expected)
  const returned = await observed()
  assert.equal(returned.rect.x, main.rect.x); assert.equal(returned.rect.width, main.rect.width)
  assert.equal(returned.rect.y, main.rect.y); assert.equal(returned.rect.height, main.rect.height)
  assert.equal(returned.fontSize, main.fontSize); assert.equal(returned.lineHeight, main.lineHeight)
  await capture('06-mobile-same-editor-main-390-light')
  await resize(390, 560)
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await until('matchMedia("(prefers-reduced-motion: reduce)").matches')
  await capture('07-mobile-same-editor-short-reduced-motion')
  const original = await saved()
  assert.equal(original.body, expected); assert.equal(original.sessionB, '原 Session B 草稿，独立保留。')
  assert.equal(await read('mobileProductScene.facts().calls.filter(c=>["agent.open","sdk.submitAgentPrompt","space.mote.dialogue.input.submit"].includes(c.method)).length'), 0)
  result.operations.push({ action: 'same-editor-reading-welcome-main-no-input-replay', ...original, main, returned })
  result.gaps.push('Actual browser selection, text input, Device persistence and two private OS processes; SDK/role/history ports are typed private observations. This does not prove a physical phone keyboard/IME or a vendor native semantic recovery.')
}
