const assert = require('node:assert/strict')

module.exports = async ({ win, read, until, resize, tap, button, capture }) => {
  await until('document.querySelector(".mote-direct-entry")?.innerText.includes("已回复")')
  await tap('.mobile-conversation-panel [contenteditable=true]', 'Retain Main draft')
  win.webContents.insertText('保留主对话草稿。')
  await until('document.querySelector("[contenteditable=true]")?.textContent.includes("保留主对话草稿")')
  await read('window.originalDirectEditor=document.querySelector("[contenteditable=true]")')
  await until('document.querySelector(".mote-assignment-progress")?.innerText.includes("等待接收")')
  await capture('mobile-main-private-summary')
  await tap('.mote-assignment-progress button', 'Open the assignment shown in Main')
  await until('document.querySelector(".mote-direct-assignment [data-direct-message-id=another-private-assignment]")')
  await capture('mobile-main-assignment-progress-details')
  await button('返回私聊', '[role=dialog]')
  await until('!!document.querySelector("[data-direct-message-id=original-private-report]")')
  await button('关闭私聊', '[role=dialog]')
  await until('!document.querySelector(".mote-direct-panel")')
  await tap('.mote-direct-entry__summary', 'Open original private thread from summary')
  await until('!!document.querySelector("[data-direct-message-id=original-private-report]")')
  const controls = await read('[...document.querySelectorAll(".mote-direct-panel > header button")].map(button => button.getBoundingClientRect().toJSON())')
  assert.equal(controls.length, 2)
  assert.ok(controls.every(control => control.width >= 44 && control.height >= 44))
  await capture('mobile-private-thread-detail')
  await button('全部私聊', '[role=dialog]')
  await until('document.querySelector(".mote-direct-panel .mote-direct-row")?.innerText.includes("资料整理")')
  await capture('mobile-private-thread-list')
  await resize(320, 660)
  await read('mobileProductScene.setAppearance("light")')
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await tap('.mote-direct-panel .mote-direct-row', 'Read the same private thread in a narrow window')
  await until('!!document.querySelector("[data-direct-message-id=original-private-report]")')
  assert.equal(await read('getComputedStyle(document.querySelector(".mote-direct-panel")).animationName'), 'none')
  await capture('mobile-private-thread-narrow')
  await tap('[data-direct-message-id=another-private-assignment] [data-open-assignment]', 'Read the exact later assignment')
  await until('document.querySelector(".mote-direct-assignment")?.innerText.includes("暂无回报")')
  assert.equal(await read('!!document.querySelector(".mote-direct-assignment [data-direct-message-id=original-private-report]")'), false)
  await capture('mobile-private-forward-assignment')
  await button('返回私聊', '[role=dialog]')
  await button('查看原作业', '[role=dialog]')
  await until('!!document.querySelector("[data-direct-message-id=original-private-assignment]")')
  assert.ok(await read('document.querySelector("[data-direct-message-id=original-private-assignment]").innerText.includes("优先投递")'))
  assert.equal(await read('!!document.querySelector("[data-direct-message-id=another-private-assignment]")'), false)
  await capture('mobile-private-assignment')
  await button('发布手册截图.png', '[role=dialog]')
  await until('document.querySelector(".mote-direct-image img")?.naturalWidth === 220')
  await capture('mobile-private-assignment-image')
  const gesture = await read(`(() => {
    const body = document.querySelector('.mote-direct-assignment')
    const rect = body.getBoundingClientRect()
    return { x: Math.round(rect.x + rect.width / 2), from: Math.round(rect.bottom - 30), to: Math.round(rect.y + 70) }
  })()`)
  const touch = (type, y) => win.webContents.debugger.sendCommand('Input.dispatchTouchEvent', {
    type, touchPoints: y === undefined ? [] : [{ id: 1, x: gesture.x, y }]
  })
  await touch('touchStart', gesture.from)
  for (let frame = 1; frame <= 10; frame++) await touch('touchMove', Math.round(gesture.from + (gesture.to - gesture.from) * frame / 10))
  await touch('touchEnd')
  await until(`(() => {
    const body = document.querySelector('.mote-direct-assignment')
    const report = body?.querySelector('[data-direct-message-id=original-private-report]')
    const bottom = body?.getBoundingClientRect().bottom
    const copy = report?.querySelector('p'), state = report?.querySelector('small')
    return body?.scrollTop > 0 && copy?.getBoundingClientRect().bottom <= bottom &&
      state?.textContent === '已回复' && state.getBoundingClientRect().bottom <= bottom &&
      document.querySelector('.mote-direct-panel > header').getBoundingClientRect().bottom <= body.getBoundingClientRect().top
  })()`)
  await capture('mobile-private-assignment-scrolled')
  await button('返回私聊', '[role=dialog]')
  await button('关闭私聊', '[role=dialog]')
  assert.equal(await read('document.querySelector("[contenteditable=true]")===window.originalDirectEditor'), true)
  assert.equal(await read('window.originalDirectEditor.textContent'), '保留主对话草稿。')
  const calls = await read('mobileProductScene.facts().calls')
  assert.equal(calls.filter(call => call.method === 'space.mote.direct.inspect').every(call => call.params.threadId === 'private-work-review'), true)
  assert.ok(calls.some(call => call.method === 'space.mote.direct.inspect'))
  assert.ok(calls.some(call => call.method === 'space.mote.direct.inspect' && call.params.messageId === 'original-private-assignment'))
  assert.ok(calls.some(call => call.method === 'space.mote.direct.inspect' && call.params.replyToMessageId === 'another-private-assignment'))
  assert.ok(calls.some(call => call.method === 'space.mote.direct.image.read' && call.params.imageOperationId === 'original-assignment-image'))
  assert.equal(calls.some(call => call.method === 'agent.input.submit' || call.method === 'space.mote.direct.send'), false)
}
