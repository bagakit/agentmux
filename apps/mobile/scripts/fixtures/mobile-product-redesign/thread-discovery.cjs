const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, tap, button, capture, result }) => {
  await read('window.threadDiscoveryMainEditor=document.querySelector("[contenteditable=true]")')
  await tap('.mote-conversation__related > summary', 'Open related work Threads')
  await until('document.querySelector(".mote-conversation__related")?.innerText.includes("比较两个实验方向")')
  await capture('11-mobile-related-work-390-dark')
  await tap('.mote-conversation__related .mote-work-event__summary', 'Expand original related work')
  await until('document.querySelector(".mote-conversation__related")?.innerText.includes("三份样本已读")')
  await capture('12-mobile-inline-thread-390-dark')
  await button('查看全部 Threads')
  await until('!!document.querySelector(".mobile-mote-threads .mote-threads__search input")')
  const input = '.mobile-mote-threads .mote-threads__search input'
  await tap(input, 'Search original work titles')
  win.webContents.selectAll(); await win.webContents.insertText('实验方向')
  await until('document.querySelector(".mobile-mote-threads .mote-threads__search input").value==="实验方向"')
  await until('document.querySelector(".mobile-mote-threads .mote-threads__list > li:not([hidden])")?.innerText.includes("实验方向")')
  await tap('.mobile-mote-threads .mote-work-event__summary', 'Expand the same work from search')
  await until('document.querySelector(".mobile-mote-threads")?.innerText.includes("三份样本已读")')
  await capture('13-mobile-thread-search-390-dark')
  const controls = await read('[...document.querySelectorAll(".mobile-mote-threads :is(button,summary,input)")].filter(n=>n.checkVisibility()).map(n=>({label:n.getAttribute("aria-label")||n.textContent,tag:n.tagName,rect:n.getBoundingClientRect().toJSON()}))')
  for (const control of controls) assert.ok(control.rect.width >= 44 && control.rect.height >= 44, 'Original Threads control retains 44px hit area: ' + control.label)
  result.operations.push({ action: 'thread-discovery-touch-geometry', controls })
  await tap(input, 'Search unmatched work title')
  win.webContents.selectAll(); await win.webContents.insertText('没有匹配的标题')
  await until('document.querySelector(".mobile-mote-threads")?.innerText.includes("没有匹配的已载入工作")')
  await capture('14-mobile-thread-no-match-390-dark')
  await tap(input, 'Clear work search'); win.webContents.selectAll(); await win.webContents.insertText('')
  await until('document.querySelector(".mobile-mote-threads .mote-threads__search input").value===""')
  await button('Discussion')
  assert.equal(await read('document.querySelector("[contenteditable=true]")===window.threadDiscoveryMainEditor'), true, 'Original Main editor returns after same-event discovery')
  await tap('.mote-conversation__related > summary', 'Collapse related work')
}
