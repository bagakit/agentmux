const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, resize, tap, button, capture, result }) => {
  result.gaps.push('Welcome/history/policy capture uses controlled Space/Mote/SDK facts. Bounded history here is a controlled response, not proof of the real Host range owner; actual Core/File/Device tests provide that behavior evidence. No microphone or live Session is used.')
  await read('mobileProductScene.prepareMoteStart("empty")')
  await until('!!document.querySelector(".mote-start [contenteditable=true]")')
  for (const [width, height, mode] of [[390,844,'light'], [320,760,'dark']]) {
    await resize(width,height); await read(`mobileProductScene.setAppearance(${JSON.stringify(mode)})`)
    await capture(`mote-start-empty-${width}-${mode}`)
  }
  await tap('.mote-start [contenteditable=true]', 'Write a Mote-scoped welcome draft')
  await win.webContents.insertText('想一起把这个想法变成一个小实验。')
  await until('mobileProductScene.facts().record.conversation.drafts.some(([key,value])=>key.includes("mote-main-start")&&value.includes("小实验"))')
  await resize(390,560); await read('mobileProductScene.setAppearance("light")'); await capture('mote-start-draft-390-short-light')
  await read('mobileProductScene.prepareMoteStart("new")')
  await until('!document.querySelector(".mote-start")&&document.querySelector("[data-mote-discussion]")')
  await button('当前对话操作'); await button('新一轮', '.mobile-sheet')
  await until('document.querySelector(".mote-start")?.dataset.mode==="new"')
  await resize(390,844); await read('mobileProductScene.setAppearance("dark")'); await capture('mote-start-new-390-dark')
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>["agent.open","space.mote.dialogue.setup.advance"].includes(call.method)).length'),0,'Viewing and writing a welcome never launches or sends')
  await read('document.querySelector(".mote-start").scrollTop=document.querySelector(".mote-start").scrollHeight')
  await capture('mote-start-history-list-390-dark')
  assert.equal(await read('document.querySelectorAll(".mote-start-history [data-mote-period]").length'),2,'Two tenures of one Session retain separate period rows')
  await tap('.mote-start-history li:first-child button', 'Open one exact original period')
  await until('!!document.querySelector("[aria-label=原主对话历史] [data-mote-period]")')
  await resize(320,760); await capture('mote-start-history-detail-320-dark')
  await read('mobileProductScene.prepareMoteStart("unknown")')
  await until('!document.querySelector(".mote-start")&&document.querySelector(".mobile-conversation-slot:not([hidden])")')
  await resize(390,844); await read('mobileProductScene.setAppearance("light")')
  await button('Mote', '.mobile-navigation')
  assert.equal(await read('!!document.querySelector(".mote-start")'),false,'An unconfirmed directory cannot cover the healthy existing Main with an empty welcome')
  await capture('mote-start-unknown-keeps-reader-390-light')
  await tap('.mobile-mote-source-status > summary', 'Read original role and configuration reasons')
  await capture('mote-start-unknown-details-390-light')
  const originalStarts = await read('mobileProductScene.facts().calls.filter(call=>["agent.open","space.mote.dialogue.setup.advance"].includes(call.method)).length')
  const originalReads = await read('mobileProductScene.facts().calls.filter(call=>call.method==="space.ls").length')
  await button('重新核对主对话信息', '.mobile-mote-source-status')
  await until(`mobileProductScene.facts().calls.filter(call=>call.method==="space.ls").length>${originalReads}`)
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>["agent.open","space.mote.dialogue.setup.advance"].includes(call.method)).length'),originalStarts,'Checking source information never creates or advances a Main')
  await read('mobileProductScene.prepareMoteStart("policy")')
  await until('!!document.querySelector(".mobile-session-identity.mobile-mote-heading")')
  await tap('.mobile-session-identity.mobile-mote-heading', 'Open original Mote Profile')
  await button('编辑快捷配置', '.mobile-mote-profile')
  await until('document.querySelector("[aria-label=自动流转策略]")?.value==="keep-current"')
  await read('mobileProductScene.setAppearance("light");document.querySelector(".mobile-sheet").scrollTop=0')
  await capture('mote-start-policy-manual-390-light')
  await read('(()=>{const input=document.querySelector("[aria-label=自动流转策略]");input.value="idle";input.dispatchEvent(new Event("change",{bubbles:true}))})()')
  await tap('[aria-label="对话空闲时长（分钟）"]', 'Edit original rollover idle duration')
  await win.webContents.insertText('12')
  await resize(320,760); await read('mobileProductScene.setAppearance("dark");document.querySelector("[aria-label=自动流转策略]").scrollIntoView({block:"start"})')
  await capture('mote-start-policy-idle-320-dark')
  await resize(390,560); await read('document.querySelector(".mobile-sheet").scrollTop=document.querySelector(".mobile-sheet").scrollHeight')
  await capture('mote-start-policy-save-390-short-dark')
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>["agent.open","space.mote.dialogue.setup.advance"].includes(call.method)).length'),0)
  result.operations.push({action:'mote-start-complete-controlled-subset', draftAndOwner:await read('mobileProductScene.facts().record.conversation.drafts'), periodCount:2})
}
