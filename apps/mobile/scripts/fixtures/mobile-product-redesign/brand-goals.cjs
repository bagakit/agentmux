const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, resize, tap, button, capture, result }) => {
  const start = await read('mobileProductScene.facts().calls.length')
  await button('Goals', '.mobile-navigation')
  await until('!!document.querySelector(".mobile-goals-start") && !!document.querySelector(".mobile-goals-list button")')
  const artReady = async () => until('[...document.querySelectorAll(".mobile-goals:not([hidden]) img")].filter(n=>n.getClientRects().length).every(n=>n.complete&&n.naturalWidth>0)')
  const shots = async (name, both = true) => {
    for (const [width, height, appearance] of both ? [[390,844,'dark'],[390,844,'light'],[320,760,'dark'],[320,760,'light']] : [[320,760,'dark'],[390,844,'light']]) {
      await resize(width,height); await read(`mobileProductScene.setAppearance(${JSON.stringify(appearance)})`)
      if (name.startsWith('proposal')) {
        await read('document.querySelector(".mobile-goal-discussion-heading").scrollIntoView({block:"center"})')
        const rect=await read('document.querySelector(".mobile-goal-discussion-heading").getBoundingClientRect().toJSON()')
        assert.ok(rect.top>=52&&rect.bottom<=height-60,'The actual proposal brand and discussion entry are inside the viewport')
      }
      await artReady()
      const facts = await read(`(()=>{const g=document.querySelector('.mobile-goals:not([hidden])');return {art:[...g.querySelectorAll('img')].filter(n=>n.getClientRects().length).map(n=>({src:n.getAttribute('src'),width:n.naturalWidth,rect:n.getBoundingClientRect().toJSON()})),buttons:[...g.querySelectorAll('button')].filter(n=>n.getClientRects().length).map(n=>({label:n.getAttribute('aria-label')||n.textContent,height:n.getBoundingClientRect().height}))}})()`)
      assert.ok(facts.art.length, 'The current Goal workface uses existing brand art')
      for(const b of facts.buttons) assert.ok(b.height>=44,'Goal actions retain touch targets: '+b.label)
      result.brandGoals.push({name,width,appearance,facts})
      await capture(`brand-goals-${name}-${width}-${appearance}`)
    }
  }
  result.brandGoals=[]
  await shots('directory')
  await button('开始新目标', '.mobile-goals')
  await until('!!document.querySelector(".mobile-goal-create__form:not([hidden])")')
  assert.equal(await read('document.activeElement.getAttribute("aria-label")'),'新目标项目')
  assert.equal(await read('!!document.querySelector(".mobile-goals-start__create")'),false)
  await shots('create',false)
  await button('新建目标', '.mobile-goals')
  await read('mobileProductScene.setBrandGoalScene("empty")')
  await button('刷新目标','.mobile-goals')
  await until('!!document.querySelector(".mobile-goals-start--empty")')
  await shots('empty')
  await read('mobileProductScene.setBrandGoalScene("pending")')
  await button('Goals','.mobile-navigation')
  await until('document.querySelector(".mobile-goals:not([hidden])")?.textContent.includes("目标列表尚未确认")')
  assert.equal(await read('!!document.querySelector(".mobile-goals-start--empty")'),false,'An unconfirmed list is never presented as empty')
  await shots('unconfirmed',false)
  await read('mobileProductScene.releaseBrandGoalRead()')
  await until('document.querySelector(".mobile-goals:not([hidden])")?.textContent.includes("读取目标失败")')
  assert.equal(await read('!!document.querySelector(".mobile-goals-start--empty")'),false)
  await shots('error',false)
  await read('mobileProductScene.setBrandGoalScene("long")')
  await button('刷新目标','.mobile-goals')
  await until('!!document.querySelector(".mobile-goals-list button")')
  await shots('long-title',false)
  await tap('.mobile-goals-list button','Open the original Goal proposal')
  await until('!!document.querySelector(".mobile-goal-discussion-heading img")')
  await shots('long-detail',false)
  await shots('proposal')
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]})
  await shots('proposal-reduced-motion',false)
  await read('mobileProductScene.prepareQuietRunStatus()')
  await button('Focus','.mobile-navigation')
  await until('!!document.querySelector(".mobile-needs-you-card[data-reason=error]")')
  for (const [width,height,appearance] of [[320,760,'dark'],[390,844,'light']]) {
    await resize(width,height); await read(`mobileProductScene.setAppearance(${JSON.stringify(appearance)})`)
    assert.equal(await read('[...document.querySelectorAll(".mobile-needs-you-card")].every(n=>getComputedStyle(n).boxShadow==="none")'),true)
    await capture(`brand-focus-error-reduced-motion-${width}-${appearance}`)
  }
  const writes=await read(`mobileProductScene.facts().calls.slice(${start}).filter(c=>/submitAgentPrompt|respondAgentInteraction|signalAgent|resumeAgent|performAgentContinuity/.test(c.method)||['goal.create','goal.discuss','goal.confirm','goal.accept','agent.open','agent.resume'].includes(c.method))`)
  assert.deepEqual(writes,[],'Brand rendering and form disclosure do not dispatch business mutations')
}
