const assert = require('node:assert/strict')

module.exports = async ({ read, until, resize, tap, button, capture, result }) => {
  result.creationUpdateBoundary = 'Actual MobileApp, creation form, DeviceWorkface and update safety provider. A controlled finite SDK creation reply is not a Host disk, Native creation or running Session claim. The real local form consumes and retains it. The original connection-preflight port waits, then rejects; no HTTP entry, navigation or successful reload is claimed. HTML select change is a DOM simulation; buttons use CDP touch, not a physical phone.'
  await until('typeof mobileProductScene !== "undefined" && mobileProductScene.facts().record.host?.hostId === "relay-original"')
  await read('mobileProductScene.prepareCreationUpdate()')
  await until('!!document.querySelector(".mobile-web-update-notice:not([hidden])")')
  const originalSessions = await read('mobileProductScene.facts().sessionIds')
  const unknown = await read('mobileProductScene.seedCreationRecovery()')
  await button('Space', '.mobile-navigation'); await button('资料工作区', '.mobile-spatial-panel')
  await button('在此启动位新建 Agent', '.mobile-spatial-panel')
  await until(`document.querySelector('select[aria-label="新 Agent 执行器"] option[value="fixture-original"]')`)
  await read(`(()=>{const select=document.querySelector('select[aria-label="新 Agent 执行器"]');select.value='fixture-original';select.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  await until(`document.querySelector('select[aria-label="新 Agent 执行器"]').value === 'fixture-original'`)
  result.operations.push({ action: 'original-html-select-change', field: '新 Agent 执行器', value: 'fixture-original' })
  await button('另建 Agent（保留待核对项）', '.mobile-agent-create')
  await until(`mobileProductScene.facts().record.agentCreates?.some(item=>item.input.operationId!==${JSON.stringify(unknown.input.operationId)}&&item.phase==='confirmed')`)
  await until('document.querySelector(".mobile-agent-create").textContent.includes("Agent 已创建")')
  const confirmed = await read('mobileProductScene.readSavedWorkface()')
  assert.equal(confirmed.issue, null)
  assert.equal(confirmed.record.agentCreates.length, 2)
  assert.deepEqual(confirmed.record.agentCreates.find(item => item.input.operationId === unknown.input.operationId), unknown)
  const created = confirmed.record.agentCreates.find(item => item.input.operationId !== unknown.input.operationId)
  assert.equal(created.phase, 'confirmed'); assert.equal(created.input.content.executorId, 'fixture-original')
  assert.equal(created.input.content.prompt, undefined)
  assert.equal(created.agentSessionId, 'controlled-created-session')
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>call.method === "agent.open").length'), 1)
  await resize(390, 844)
  await read('document.querySelector(".mobile-agent-create").scrollTop=document.querySelector(".mobile-agent-create").scrollHeight')
  await capture('creation-confirmed-before-update')
  await button('关闭新建 Agent', '.mobile-agent-create')
  await until('!document.querySelector(".mobile-agent-create")')
  await button('手机设置与连接')
  await until('!!document.querySelector(".mobile-web-update-settings")')
  const original = await read('({href:location.href,record:mobileProductScene.readSavedWorkface().record})')
  await button('载入最新版', '.mobile-web-update-settings')
  await until('mobileProductScene.facts().calls.some(call=>call.method === "fixture.update-connection-preflight")')
  await until(`Array.from(document.querySelectorAll('.mobile-web-update-settings button')).some(button=>button.disabled&&button.textContent==='正在保全…')`)
  await read('document.querySelector(".mobile-web-update-settings").scrollIntoView({block:"center"})')
  await capture('creation-confirmed-update-preflight')
  await read('mobileProductScene.failCreationUpdatePreflight()')
  await until('document.querySelector(".mobile-web-update-settings").textContent.includes("原连接或新版入口暂时无法确认")')
  const final = await read('({href:location.href,saved:mobileProductScene.readSavedWorkface(),facts:mobileProductScene.facts()})')
  assert.equal(final.href, original.href, 'The original page remains after the explicit preflight rejection')
  assert.equal(final.saved.issue, null)
  for (const key of ['selectedSessionId', 'presentation', 'conversation', 'agentCreates', 'host']) assert.deepEqual(final.saved.record[key], original.record[key], 'Original ' + key + ' remains')
  assert.deepEqual(final.facts.calls.filter(call => call.method === 'agent.open').map(call => call.params.operationId), [created.input.operationId])
  assert.equal(final.facts.calls.filter(call => call.method === 'fixture.update-connection-preflight').length, 1)
  assert.equal(final.facts.calls.filter(call => ['sdk.submitAgentPrompt', 'sdk.ensureAgentContinuity'].includes(call.method)).length, 0)
  assert.deepEqual(final.facts.sessionIds, originalSessions, 'No Native or running Session facts are manufactured for this capture')
  result.confirmedCreationUpdate = { unknown, created, localRecordConfirmed: true, originalPreflightCalls: 1,
    end: 'controlled-preflight-rejected-original-page-retained', successfulReload: false, actualHostCreation: false }
}
