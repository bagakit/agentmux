const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, resize, tap, button, capture, result }) => {
  await until('document.querySelector(".mobile-mote-team-summary")?.innerText.includes("团队 2")')
  const original = await read('mobileProductScene.facts().record.selectedSessionId')
  assert.equal(original, 'session-mote')
  await tap('.mobile-conversation-panel [contenteditable=true]', 'Retain main discussion draft')
  win.webContents.insertText('先把这一轮想法保留，回来继续和主 Agent 讨论。')
  await until('mobileProductScene.facts().record.conversation.drafts.some(([,text])=>text.includes("先把这一轮想法保留"))')
  const teamTarget = await read('document.querySelector(".mobile-mote-team-trigger").getBoundingClientRect().toJSON()')
  assert.ok(teamTarget.width >= 44 && teamTarget.height >= 44, 'Actual team entry preserves touch geometry')
  await capture('mote-cooperation-main-390')
  await button('查看本 Mote 团队')
  await until('document.querySelector(".mobile-mote-team-panel")?.innerText.includes("请确认本次资料读取")')
  await capture('mote-cooperation-team-390')
  const scoped = await read('[...document.querySelectorAll(".mobile-mote-team-section:last-child [data-mote-member]")].map(node=>node.dataset.moteMember)')
  assert.deepEqual(scoped, ['session-mote', 'session-waiting'])
  await button('打开原成员 · 资料整理', '[role=dialog]')
  await until('mobileProductScene.facts().record.selectedSessionId==="session-waiting"')
  await until('document.querySelector(".mobile-mote-recipient")?.innerText.includes("成员")')
  await capture('mote-cooperation-member-request-390')
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>call.method==="sdk.submitAgentPrompt"||call.method==="sdk.respondAgentInteraction").length'), 0)
  await button('回主对话')
  await until('mobileProductScene.facts().record.selectedSessionId==="session-mote"')
  assert.ok(await read('document.querySelector("[contenteditable=true]").textContent.includes("先把这一轮想法保留")'))
  await read('mobileProductScene.prepareCooperationLongNames()')
  await button('查看本 Mote 团队'); await button('刷新本 Mote 团队', '[role=dialog]')
  await until('document.querySelector("[role=dialog]")?.innerText.includes("负责资料阅读、证据核对与长名称展示的研究成员")')
  await resize(320, 760); await capture('mote-cooperation-long-team-320')
  await button('回到主对话', '[role=dialog]')
  await until('document.querySelector(".mobile-mote-recipient")?.innerText.includes("协调方案")')
  await capture('mote-cooperation-long-main-320')
  await read('mobileProductScene.setAppearance("light")')
  await capture('mote-cooperation-long-main-light-320')
  await button('查看本 Mote 团队'); await capture('mote-cooperation-long-team-light-320')
  await button('关闭面板', '[role=dialog]')
  await read('mobileProductScene.offline()')
  await button('查看本 Mote 团队')
  await until('document.querySelector("[role=dialog]")?.innerText.includes("连接暂不可用")')
  await capture('mote-cooperation-retained-team-320')
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>call.method==="sdk.submitAgentPrompt"||call.method==="sdk.respondAgentInteraction").length'), 0)
  result.cooperation = { original, members: scoped, navigationOnly: true, retainedMainDraft: true }
}
