const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, resize, tap, button, capture, result }) => {
  await until('document.querySelector(".mobile-mote-context .mobile-mote-team-button__label")?.textContent==="团队 2"')
  const original = await read('mobileProductScene.facts().record.selectedSessionId')
  assert.equal(original, 'session-mote')
  await tap('.mobile-conversation-panel [contenteditable=true]', 'Retain main discussion draft')
  win.webContents.insertText('先把这一轮想法保留，回来继续和主 Agent 讨论。')
  await until('mobileProductScene.facts().record.conversation.drafts.some(([,text])=>text.includes("先把这一轮想法保留"))')
  const teamTarget = await read('document.querySelector(".mobile-mote-context .mobile-mote-team-button").getBoundingClientRect().toJSON()')
  assert.ok(teamTarget.width >= 44 && teamTarget.height >= 44, 'Actual team entry preserves touch geometry')
  await capture('mote-cooperation-main-390')
  await button('查看本 Mote 团队')
  await until('document.querySelector(".mobile-mote-team-panel")?.innerText.includes("请确认本次资料读取")')
  await capture('mote-cooperation-team-390')
  // The hidden Threads page keeps its own members-only copy; the open team sheet is the subject.
  const scoped = await read('[...document.querySelectorAll("[role=dialog] .mobile-mote-team-section:last-child [data-mote-member]")].map(node=>node.dataset.moteMember)')
  assert.deepEqual(scoped, ['session-mote', 'session-waiting'])
  await button('打开成员 · 资料整理', '[role=dialog]')
  await until('mobileProductScene.facts().record.selectedSessionId==="session-waiting"')
  // The scene's saved main is not confirmed: the member's role stays pending, and no strip shortcut claims a main.
  await until('document.querySelector(".mobile-mote-context[data-variant=member] .mobile-mote-context__role")?.innerText.trim()==="主角色待核对"')
  assert.equal(await read('document.querySelector(".mobile-mote-main-return")'), null)
  assert.equal(await read('document.querySelector(".mobile-navigation")'), null, 'A member thread is drilled; the tab bar stays on root pages')
  await capture('mote-cooperation-member-request-390')
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>call.method==="sdk.submitAgentPrompt"||call.method==="sdk.respondAgentInteraction").length'), 0)
  await button('返回 Threads', '.mobile-header')
  await until('document.querySelector(".mobile-mote-context[data-variant=main] [role=tab][aria-selected=true]")?.textContent==="Threads"&&!!document.querySelector(".mobile-navigation")')
  await button('Discussion', '.mobile-mote-context')
  await until('mobileProductScene.facts().record.selectedSessionId==="session-mote"')
  assert.ok(await read('document.querySelector("[contenteditable=true]").textContent.includes("先把这一轮想法保留")'))
  await read('mobileProductScene.prepareCooperationLongNames()')
  await button('查看本 Mote 团队'); await button('刷新本 Mote 团队', '[role=dialog]')
  await until('document.querySelector("[role=dialog]")?.innerText.includes("负责资料阅读、证据核对与长名称展示的研究成员")')
  await resize(320, 760); await capture('mote-cooperation-long-team-320')
  await button('关闭面板', '[role=dialog]')
  // The Mote main names its Mote; the strip under it never repeats that name.
  await until('document.querySelector(".mobile-header .mobile-mote-heading .mobile-session-title")?.innerText===mobileProductScene.facts().record.presentation.identity.mote.name')
  assert.ok(!await read('document.querySelector(".mobile-mote-context").innerText.includes(mobileProductScene.facts().record.presentation.identity.mote.name)'))
  // From the narrowest accepted width to common phones, the source pill never covers the team entry and the Mote's name stays whole.
  for (const width of [320, 360, 375, 390]) {
    await resize(width, 760)
    const geometry = await read(`(()=>{const rect=selector=>document.querySelector(selector).getBoundingClientRect(),title=document.querySelector('.mobile-header .mobile-session-title'),label=document.querySelector('.mobile-mote-context .mobile-mote-source-status__label'),pill=document.querySelector('.mobile-mote-context .mobile-mote-source-status > summary'),team=rect('.mobile-mote-context .mobile-mote-team-button');return {pillRight:Math.max(...[pill,...pill.children].filter(node=>node.getClientRects().length).map(node=>node.getBoundingClientRect().right)),label:{height:label.getBoundingClientRect().height,font:parseFloat(getComputedStyle(label).fontSize),client:label.clientWidth,scroll:label.scrollWidth},team:{left:team.left,right:team.right,width:team.width,height:team.height},title:{client:title.clientWidth,scroll:title.scrollWidth}}})()`)
    result.operations.push({ action: 'mote-strip-header-geometry', width, ...geometry })
    assert.ok(geometry.pillRight <= geometry.team.left + 0.5, `Everything the source pill paints stays clear of the team entry at ${width}px`)
    assert.ok(geometry.label.height < geometry.label.font * 2 && geometry.label.scroll <= geometry.label.client + 1, `The source pill keeps its short label on one whole line at ${width}px`)
    assert.ok(geometry.team.width >= 44 && geometry.team.height >= 44 && geometry.team.right <= width, `The team entry keeps its full touch target at ${width}px`)
    assert.ok(geometry.title.scroll <= geometry.title.client + 1, `The Mote name stays whole at ${width}px`)
  }
  await resize(320, 760)
  await capture('mote-cooperation-long-main-320')
  await read('mobileProductScene.setAppearance("light")')
  await capture('mote-cooperation-long-main-light-320')
  await button('查看本 Mote 团队'); await capture('mote-cooperation-long-team-light-320')
  await button('关闭面板', '[role=dialog]')
  await read('mobileProductScene.offline()')
  await button('查看本 Mote 团队')
  await until('document.querySelector("[role=dialog]")?.innerText.includes("连接暂不可用")')
  await capture('mote-cooperation-retained-team-320')
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>call.method==="sdk.submitAgentPrompt"||call.method==="sdk.respondAgentInteraction").length'), 0)
  result.cooperation = { original, members: scoped, navigationOnly: true, retainedMainDraft: true }
}
