const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, resize, tap, button, capture, result }) => {
  result.gaps.push('Actual MobileApp/Composer/Profile Renderer; setup RPCs replay fresh real-consumer receipts, rebound to this private fixture target/request. No live Host, Provider, user App or real phone is operated. App/Host/Core/File tests prove persistence and behaviour; images do not.')
  await read('mobileProductScene.prepareMoteStart("empty")')
  await read('mobileProductScene.configureSetupRetention("welcome")')
  await until('!!document.querySelector(".mote-start [contenteditable=true]")')
  await tap('.mote-start [contenteditable=true]', 'Write original A Query')
  await win.webContents.insertText('Original A Query')
  await until('!document.querySelector(".mote-start button[aria-label=Send]").disabled')
  await button('Send', '.mote-start')
  await until('mobileProductScene.facts().calls.some(call=>call.method==="space.mote.dialogue.setup.advance")')
  await tap('.mote-start [contenteditable=true]', 'Keep later B draft while original receipt is held')
  await read('getSelection().selectAllChildren(document.querySelector(".mote-start [contenteditable=true]"))')
  await win.webContents.insertText('后来补充的 B 草稿，保留在这里。')
  await read('mobileProductScene.releaseSetupRetention()')
  await until('document.querySelector(".mote-start")?.innerText.includes("首条消息已送达。")&&document.querySelector(".mote-start")?.innerText.includes(mobileProductScene.setupRetentionIssue())')
  await tap('.mobile-mote-start-details > summary', 'Inspect the same retained welcome request')
  await until('!document.querySelector(".mobile-mote-start-details button").disabled')
  const welcomeOperation = await read('mobileProductScene.facts().calls.find(call=>call.method==="agent.open").params.operationId')
  await button('核对这次开始', '.mobile-mote-start-details')
  await until('!document.querySelector(".mobile-mote-start-details button").disabled')
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>call.method==="space.mote.dialogue.setup.inspect").at(-1).params.creation.operationId'), welcomeOperation)
  assert.equal(await read('mobileProductScene.facts().record.selectedSessionId'), null)
  assert.equal(await read('document.querySelector(".mote-start [contenteditable=true]").innerText'), '后来补充的 B 草稿，保留在这里。')
  for (const [width, height] of [[320, 900], [768, 1000]]) {
    await resize(width, height)
    await read('mobileProductScene.setAppearance("light");document.querySelector(".mote-start__notice").scrollIntoView({block:"nearest"})')
    await capture(`main-retention-welcome-${width}`)
  }
  const before = await read('mobileProductScene.facts().calls.filter(call=>call.method==="agent.open").length')
  await read('mobileProductScene.prepareMoteStart("empty")')
  await read('mobileProductScene.configureSetupRetention("profile")')
  await until('!!document.querySelector(".mobile-session-identity.mobile-mote-heading")')
  await tap('.mobile-session-identity.mobile-mote-heading', 'Open the actual Mote Profile parent')
  await until('!!document.querySelector(".mobile-mote-setup")')
  await button('新建 Main Agent', '.mobile-mote-setup')
  await until('document.querySelector(".mobile-mote-setup")?.innerText.includes("Main 已绑定")&&document.querySelector(".mobile-mote-setup")?.innerText.includes(mobileProductScene.setupRetentionIssue())')
  await tap('.mobile-mote-setup details > summary', 'Open original setup operation and recovery actions')
  for (const [width, height] of [[320, 900], [768, 1000]]) {
    await resize(width, height)
    await read('document.querySelector(".mobile-mote-setup").scrollIntoView({block:"start"})')
    await capture(`main-retention-profile-${width}`)
  }
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>call.method==="agent.open").length'), before + 1)
  result.operations.push({ action: 'retention-disclosure-original-successes', welcomeOperation, originalRequestInspection: true, noExtraCreation: true })
}
