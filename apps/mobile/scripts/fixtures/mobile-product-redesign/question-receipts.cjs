const assert = require('node:assert/strict')

module.exports = async ({ win, read, until, resize, tap, button, capture, result }) => {
  const request = '[data-request-id="request-original"]'
  const selector = JSON.stringify(request)
  const status = (text) => `document.querySelector(${selector})?.textContent.includes(${JSON.stringify(text)})`
  const complete = expected => `document.querySelector(${selector})?.getAttribute("data-completed") === "${expected}"`
  const details = request + ' .agent-interaction__details-toggle'
  await win.webContents.debugger.sendCommand('Emulation.setFocusEmulationEnabled', { enabled: true })
  await until('Boolean(window.mobileProductScene)')
  const selected = await read('mobileProductScene.facts().record.selectedSessionId')
  if (selected !== 'session-waiting') {
    await button('Focus', '.mobile-navigation')
    await button('资料整理', '.mobile-spatial-panel')
  }
  await until(`Boolean(document.querySelector(${selector}))`)
  await resize(320, 760)
  await capture('request-dark-narrow')
  await button('允许本次读取', request)
  await until(status('答复已保存'))
  assert.ok(await read(complete(false)))
  await capture('saved-dark-narrow')
  await read('mobileProductScene.setPermissionReceiptStage("unknown");mobileProductScene.setAppearance("light")')
  await resize(390, 844)
  await button('查询答复结果', request)
  await until(status('还没确认答复是否送达'))
  assert.ok(await read(complete(false)))
  await capture('unknown-light')
  await read('mobileProductScene.setPermissionReceiptStage("completed")')
  await button('查询答复结果', request)
  await until(complete(true))
  await capture('completion-light', { motion: true })
  await tap(details, 'Open original completed request')
  await until(`document.querySelector(${JSON.stringify(details)})?.getAttribute("aria-expanded")==="true"`)
  const toggle = JSON.stringify(details)
  await read(`document.querySelector(${toggle}).focus()`)
  for (const type of ['keyDown', 'keyUp']) await win.webContents.debugger.sendCommand('Input.dispatchKeyEvent', {
    type, key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, ...(type === 'keyDown' ? { text: '\r' } : {})
  })
  assert.ok(await read(`document.activeElement===document.querySelector(${toggle})`))
  await until(`document.querySelector(${JSON.stringify(details)})?.getAttribute("aria-expanded")==="false"`)
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await until('matchMedia("(prefers-reduced-motion: reduce)").matches')
  for (const type of ['keyDown', 'keyUp']) await win.webContents.debugger.sendCommand('Input.dispatchKeyEvent', {
    type, key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, ...(type === 'keyDown' ? { text: '\r' } : {})
  })
  await until(`document.querySelector(${JSON.stringify(details)})?.getAttribute("aria-expanded")==="true"`)
  assert.ok(await read(`!document.querySelector(${selector}).getAnimations({subtree:true}).some(a=>a.playState==="running" && a.effect?.getComputedTiming().duration>0)`))
  await capture('completed-detail-reduced')
  await read('mobileProductScene.settleWaitingAnswer()')
  await until('!document.querySelector(".mobile-conversation__interaction")')
  await button('沿用原资料', '.agent-interaction--async')
  await button('发送答案', '.agent-interaction--async')
  await until('document.querySelector("[data-question-state=unknown] .agent-question__original")')
  await capture('native-question-unknown')
  await button('继续原发送', '.agent-interaction--async')
  await until('document.querySelector("[data-question-state=submitted]")')
  await capture('native-question-submitted')
  const calls = await read('mobileProductScene.facts().calls.filter(call=>["sdk.respondAgentInteraction","sdk.inspectAgentInteractionOperation","sdk.replySessionQuestion"].includes(call.method))')
  const [response, ...after] = calls
  assert.equal(response.method, 'sdk.respondAgentInteraction')
  assert.equal(response.params.expectedRequest.id, 'request-original')
  assert.equal(after.length, 4)
  for (const lookup of after.slice(0, 2)) assert.deepEqual(lookup.params, { agentSessionId: response.params.agentSessionId, operationId: response.params.operationId })
  const [first, second] = after.slice(2)
  assert.equal(first.method, 'sdk.replySessionQuestion')
  assert.equal(second.method, first.method)
  assert.equal(first.params.recordId, 'original-question')
  assert.deepEqual(second.params, first.params)
  result.operations.push({ action: 'original-receipt-calls', calls })
}
