const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, resize, tap, button, capture, result }) => {
  await until('document.querySelector(".mobile-mote-team-summary")?.innerText.includes("团队 2")')
  await tap('.mobile-conversation-panel [contenteditable=true]', 'Keep original draft during Host qualification')
  win.webContents.insertText('Host 归属未知时保留这份原主稿。')
  await read('mobileProductScene.prepareCooperationHostBoundaries()')
  await button('查看本 Mote 团队'); await button('刷新本 Mote 团队', '[role=dialog]')
  await until('document.querySelectorAll(".mobile-mote-team-section:last-child [data-mote-member=session-waiting]").length===3')
  const rows = await read('[...document.querySelectorAll(".mobile-mote-team-section:last-child [data-mote-member=session-waiting]")].map(node=>({host:node.dataset.moteHost,key:node.dataset.moteMemberKey,text:node.innerText}))')
  assert.equal(new Set(rows.map(row => row.key)).size, 3)
  assert.deepEqual(new Set(rows.map(row => row.host)), new Set(['host-original', 'foreign-host', '']))
  assert.ok(rows.every(row => !row.text.includes('资料整理')), 'Unqualified bare-SID metadata is not lent across Hosts')
  await resize(320, 760)
  await capture('mote-host-boundaries-distinct-hosts-320')
  await tap('.mobile-mote-team-section:last-child [data-mote-host="foreign-host"] .mobile-mote-member-open', 'Reject only the wrong original Host navigation')
  assert.equal(await read('mobileProductScene.facts().record.selectedSessionId'), 'session-mote')
  await tap('.mobile-mote-team-section:last-child [data-mote-host=""] .mobile-mote-member-open', 'Retain the unknown Host original Region')
  assert.equal(await read('mobileProductScene.facts().record.selectedSessionId'), 'session-mote')
  await tap('.mobile-mote-team-section:last-child [data-mote-host=""] .mobile-mote-member-references > summary', 'Reveal original Region and recovery')
  await tap('.mobile-mote-team-section:last-child [data-mote-host=""] .mobile-mote-member-references button', 'Refresh retained original Region without retargeting')
  assert.equal(await read('mobileProductScene.facts().record.selectedSessionId'), 'session-mote')
  await capture('mote-host-boundaries-original-references-320')
  await button('关闭面板', '[role=dialog]')
  assert.ok(await read('document.querySelector("[contenteditable=true]").textContent.includes("Host 归属未知时保留")'))
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>call.method==="sdk.submitAgentPrompt"||call.method==="sdk.respondAgentInteraction"||call.method==="sdk.ensureAgentContinuity").length'), 0)
  result.hostBoundaries = { exactRows: rows, wrongAndUnknownTargetsRetained: true, originalDraftRetained: true }
}
