const assert = require('node:assert/strict')

module.exports = async ({ win, read, until, resize, tap, button, capture, result }) => {
  await button('Focus', '.mobile-navigation')
  const initial = await read('mobileProductScene.facts()')
  await until(`document.querySelectorAll('.mobile-focus-available .mobile-agent-row__open').length===${initial.sessionIds.length}`)
  result.focusAvailability = { observations: [], boundary: 'Actual MobileApp and original Hosted SDK methods with controlled missing presentation; no live Mac/Relay/Runtime or physical phone claim.' }
  const rows = () => read(`(()=>{const facet=document.querySelector('.mobile-focus-facet');return [...facet.querySelectorAll('.mobile-agent-row__open')].map(n=>{const r=n.getBoundingClientRect(),hit=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2);return {text:n.innerText,rect:r.toJSON(),visible:!!n.getClientRects().length&&!n.closest('[hidden],[inert],details:not([open])'),hit:n===hit||n.contains(hit)}})})()`)
  for (const [width, height, theme] of [[390, 844, 'dark'], [320, 568, 'light']]) {
    await resize(width, height); await read(`mobileProductScene.setAppearance(${JSON.stringify(theme)})`)
    const observed = await rows()
    assert.equal(observed.length, initial.sessionIds.length)
    assert.ok(observed.every(row => row.visible && row.hit && row.rect.height >= 44), 'Original SDK rows are actually visible/hittable without opening details')
    assert.equal(await read('document.querySelector(".mobile-focus-facet").innerText.includes("暂无会话")'), false)
    assert.equal(await read('document.querySelector("[data-workface=focus] [data-unconfirmed]")?.textContent'), '?')
    result.focusAvailability.observations.push({ phase: 'missing', width, height, theme, rows: observed })
    await capture(`focus-unconfirmed-${width}-${theme}`)
  }
  await tap('.mobile-focus-facet .mobile-directory-notice', '原 Focus 原因与处理')
  await until('!!document.querySelector(".mobile-directory-issues")')
  await tap('.mobile-directory-technical summary', '原读取技术详情')
  assert.ok(await read('document.querySelector(".mobile-directory-issues").innerText.includes("FOCUS_PRESENTATION_UNAVAILABLE")'))
  await capture('focus-unconfirmed-reason-320-light')
  await button('关闭目录信息', '.mobile-directory-issues')
  await tap('.mobile-focus-available li:first-child .mobile-agent-row__open', '继续原 SDK 会话')
  await until('!!document.querySelector(".mobile-conversation-panel:not([hidden]) [contenteditable=true]")')
  await read(`window.focusAvailabilityEditor=document.querySelector('.mobile-conversation-panel:not([hidden]) [contenteditable=true]');focusAvailabilityEditor.focus()`)
  const draft = '原目录未确认时保留这段未发送草稿。'
  await win.webContents.insertText(draft)
  await until(`mobileProductScene.facts().record.conversation.drafts.some(([,text])=>text.includes(${JSON.stringify(draft)}))`)
  const known = await read('mobileProductScene.facts()')
  assert.equal(known.record.selectedSessionId, 'session-mote')
  await button('Focus', '.mobile-navigation')
  await read('mobileProductScene.setFocusPresentationAvailable(true)')
  const count = await read('mobileProductScene.facts().calls.filter(c=>c.method==="space.ls").length')
  await button('重新读取 Focus', '.mobile-focus-facet')
  await until(`document.querySelectorAll('.mobile-focus-project .mobile-agent-row__open').length===${initial.focusPresentation.length}&&!document.querySelector('.mobile-focus-read-status')`)
  assert.deepEqual((await read(`[...document.querySelectorAll('.mobile-focus-project .mobile-agent-row__open strong')].map(n=>n.textContent)`)).sort(), initial.focusPresentation.map(row => row.name).sort(), 'Recovered Focus presents every exact original source member')
  assert.ok(await read(`mobileProductScene.facts().calls.filter(c=>c.method==='space.ls').length>${count}`))
  await resize(390, 844)
  await read(`window.focusAvailabilityRow=[...document.querySelectorAll('.mobile-focus-project .mobile-agent-row__open')].find(n=>n.querySelector('strong')?.textContent==='日常协作')`)
  assert.equal(await read('!!focusAvailabilityRow'), true)
  await capture('focus-confirmed-recovered-390-light')
  await read('mobileProductScene.setFocusPresentationAvailable(false)')
  await button('刷新空间目录', '.mobile-focus-facet')
  await until('document.querySelector(".mobile-focus-read-status")?.textContent.includes("以下是上次读取的内容")')
  assert.equal(await read('focusAvailabilityRow.isConnected&&document.querySelector(".mobile-focus-facet").contains(focusAvailabilityRow)'), true, 'Same original row DOM survives missing presentation')
  await read('mobileProductScene.setAppearance("dark")')
  await capture('focus-last-read-retained-390-dark')
  const final = await read('mobileProductScene.facts()')
  assert.deepEqual(final.record.conversation, known.record.conversation, 'Original draft, queue and receipts survive recovery and missing presentation')
  assert.deepEqual(final.sessionIds, initial.sessionIds, 'Original Session/Run references remain')
  assert.equal(final.calls.filter(call => ['sdk.ensureAgentContinuity', 'agent.open', 'sdk.submitAgentPrompt', 'sdk.respondAgentInteraction', 'sdk.signalAgent'].includes(call.method)).length, 0)
  await button('日常协作', '.mobile-focus-project')
  await until('!!document.querySelector(".mobile-conversation-panel:not([hidden]) [contenteditable=true]")')
  assert.equal(await read('document.querySelector(".mobile-conversation-panel:not([hidden]) [contenteditable=true]")===focusAvailabilityEditor'), true, 'The original mounted editor is retained')
  assert.ok(await read(`focusAvailabilityEditor.textContent.includes(${JSON.stringify(draft)})`))
  result.focusAvailability.preservation = { sameConversationRecord: true, sameSessionRunReferences: true, sameEditor: true, controls: 0 }
}
