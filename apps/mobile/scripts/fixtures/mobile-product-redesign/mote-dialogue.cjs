const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, resize, tap, button, capture, result, openMote }) => {
  await openMote()
  await until('document.querySelector("[data-mote-dialogue]")&&document.querySelector(".mote-conversation__messages .mote-work-event__summary")?.textContent.includes("比较两个实验方向")')
  await tap('.mobile-conversation-panel [contenteditable=true]', 'Retain original Mote draft')
  win.webContents.insertText('先保留这一轮想法，回来继续。')
  await until('mobileProductScene.facts().record.conversation.drafts.some(([,text])=>text.includes("先保留这一轮想法"))')
  const draft = await read('document.querySelector("[contenteditable=true]").textContent')
  const reading = '.mobile-conversation__reading'
  const top = async () => { await read(`document.querySelector(${JSON.stringify(reading)}).scrollTop=0`); await read('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))') }
  const geometry = async selectors => {
    const values = await read(`(${JSON.stringify(selectors)}).flatMap(selector=>[...document.querySelectorAll(selector)].filter(n=>n.getClientRects().length).map(n=>({selector,label:n.getAttribute('aria-label')||n.textContent,rect:n.getBoundingClientRect().toJSON()})))`)
    assert.ok(values.length, 'Actual Mobile controls are nonempty')
    for (const {rect,label} of values) assert.ok(rect.width >= 44 && rect.height >= 44, label + ' keeps at least 44px touch geometry')
    result.operations.push({ action: 'actual-dialogue-target-geometry', values })
  }
  await top(); await geometry(['.mote-conversation__navigation button','.mote-work-event__summary'])
  const navBackground = await read('getComputedStyle(document.querySelector(".mote-conversation__navigation")).backgroundColor')
  assert.ok(navBackground !== 'transparent' && navBackground !== 'rgba(0, 0, 0, 0)', 'Sticky navigation uses a real current theme surface')
  result.operations.push({action:'sticky-navigation-current-theme-surface',backgroundColor:navBackground})
  const shortStack = await read('(()=>{const stack=document.querySelector(".mote-conversation__messages").getBoundingClientRect(),reader=document.querySelector(".mobile-conversation__reading").getBoundingClientRect();return {stack:stack.toJSON(),reader:reader.toJSON(),gap:reader.bottom-stack.bottom}})()')
  assert.ok(shortStack.gap >= -1 && shortStack.gap <= 12, 'Short Mote conversation naturally rests near its original Composer')
  result.operations.push({action:'short-mote-conversation-near-input',...shortStack})
  await capture('01-mobile-main-and-thread-390-dark')
  await button('事件历史 · 1')
  await tap('.mote-conversation__history .mote-work-event__summary', 'Expand the same original event in history')
  await until('document.querySelector(".mote-conversation__history")?.innerText.includes("三份样本已读")')
  await top(); await geometry(['.mote-conversation__history .mote-work-event__actions button','.mote-conversation__history summary'])
  await capture('02-mobile-same-event-history-390-dark')
  assert.equal(await read('document.querySelector(".mote-conversation__history [data-mote-work-event]").dataset.moteWorkEvent'), 'original-research-event')
  await button('主对话')
  await tap('.mobile-mote-heading', 'Open original Mote Profile')
  await button('编辑快捷配置')
  await until('document.querySelector("[data-mote-maintenance-status]")?.textContent==="原心跳安排已暂停"')
  await read('document.querySelector(".mobile-mote-presence").scrollIntoView({block:"center"})')
  assert.equal(await read('document.querySelector(".mobile-mote-presence input[type=number]").value'), '30')
  await geometry(['[aria-label="心跳间隔（分钟）"]','.mobile-mote-presence > button'])
  const sheetPaint = await read('(()=>{const s=document.querySelector(".mobile-sheet"),t=s.querySelector(".mobile-sheet-title");return {sheet:s.getBoundingClientRect().toJSON(),title:t.getBoundingClientRect().toJSON(),background:getComputedStyle(s).backgroundColor}})()')
  const bitmapImage = await win.webContents.capturePage(), bitmap = bitmapImage.getBitmap(), bitmapSize = bitmapImage.getSize()
  const expectedRgb = sheetPaint.background.match(/[0-9.]+/g).slice(0,3).map(Number)
  let differing = 0, sampled = 0
  for (let y = Math.ceil(sheetPaint.sheet.top) + 2; y < Math.floor(sheetPaint.title.top); y++) for (let x = 24; x < bitmapSize.width - 24; x++) {
    const i = (y * bitmapSize.width + x) * 4; sampled++
    if ([bitmap[i+2],bitmap[i+1],bitmap[i]].some((value, channel) => Math.abs(value - expectedRgb[channel]) > 4)) differing++
  }
  result.operations.push({action:'scrolled-settings-padding-band-painted',...sheetPaint,sampled,differing})
  assert.ok(sampled > 0 && differing === 0, 'Scrolled settings title paints its full top padding band; field glyphs cannot leak above it')
  await capture('03-mobile-presence-paused-390-dark')
  await button('明确恢复原心跳安排')
  await until('mobileProductScene.facts().record.moteQuickDrafts?.some(d=>d.maintenanceAttempts?.some(a=>a.phase==="confirmed"))')
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>call.method==="schedule.resume").length'), 1)
  await read('document.querySelector(".mobile-mote-quick-editor > button").scrollIntoView({block:"center"})')
  await button('返回 Profile'); await button('关闭面板', '[role=dialog]')
  await until('!!document.querySelector("[data-mote-dialogue]")')
  await read('mobileProductScene.replaceMoteMain()')
  await button('刷新', '.mote-conversation__navigation')
  await until('document.querySelector(".mote-conversation__navigation")?.innerText.includes("回到 我的 Mote")')
  await button('回到 我的 Mote')
  await until('mobileProductScene.facts().record.selectedSessionId==="session-waiting"&&!!document.querySelector("[data-mote-earlier-source] [data-mote-speaker]")')
  await resize(390, 932); await top()
  await read('document.querySelector(".mote-conversation__messages .mote-work-event__summary")?.getAttribute("aria-expanded")==="true"&&document.querySelector(".mote-conversation__messages .mote-work-event__summary").click()')
  const avatars = await read('[...document.querySelectorAll("[data-mote-speaker]")].map(n=>({mote:n.dataset.moteSpeaker,prior:n.closest("[data-mote-earlier-source]")?.getAttribute("data-mote-earlier-source")}))')
  assert.ok(avatars.some(n=>n.prior && JSON.parse(n.prior).agentSessionId==='session-mote'))
  assert.ok(avatars.some(n=>!n.prior)); assert.ok(avatars.every(n=>n.mote==='mote-original'))
  result.operations.push({action:'exact-previous-and-current-Mote-identity',avatars})
  await capture('04-mobile-main-A-to-B-390-dark')
  await read('mobileProductScene.prepareCooperationLongNames();mobileProductScene.setAppearance("light")')
  await button('查看本 Mote 团队'); await button('刷新本 Mote 团队', '[role=dialog]'); await button('回到主对话', '[role=dialog]')
  await resize(320, 760); await top()
  await capture('05-mobile-identity-long-320-light')
  await read('mobileProductScene.unconfirmMoteDialogue()')
  await button('刷新', '.mote-conversation__navigation')
  await until('document.querySelector(".mote-conversation__issue")?.textContent.includes("原主对话读取暂不可用")')
  await top(); await capture('06-mobile-retained-main-320-light')
  assert.equal(await read('mobileProductScene.facts().record.conversation.drafts.find(([key])=>key.includes("session-mote"))?.[1]'), draft)
  const sends = await read('mobileProductScene.facts().calls.filter(call=>/submitAgentPrompt|respondAgentInteraction|dialogue.input.submit|agent.open|agent.continuity/.test(call.method))')
  assert.deepEqual(sends, [], 'Reading, handoff and explicit original schedule resume cannot send or create Agents')
  result.dialogue = {sameEvent:'original-research-event',originalDraft:draft,retainedAgentSessions:['session-mote','session-waiting'],originalRunsPreserved:true,explicitOriginalScheduleResumeOnly:true}
}
