const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, resize, tap, button, capture, result, openMote }) => {
  await button('Mote', '.mobile-navigation')
  await until('!!document.querySelector("[data-mote-discussion]")')
  assert.equal(await read('document.querySelector("[data-mote-discussion] [data-mote-work-event]")'), null, 'Discussion contains Main only')
  await tap('.mobile-conversation-panel [contenteditable=true]', 'Retain original Mote draft')
  win.webContents.insertText('先保留这一轮想法，回来继续。')
  await until('mobileProductScene.facts().record.conversation.drafts.some(([,text])=>text.includes("先保留这一轮想法"))')
  await read('window.moteOriginalEditor=document.querySelector("[contenteditable=true]")')
  const draft = await read('window.moteOriginalEditor.textContent')
  const geometry = async () => {
    const values = await read('[...document.querySelectorAll(".mobile-mote-navigation button")].map(n=>({label:n.textContent,rect:n.getBoundingClientRect().toJSON()}))')
    assert.equal(values.length, 3)
    for (const {rect,label} of values) assert.ok(rect.width>=44&&rect.height>=44,label+' retains touch geometry')
    assert.ok(values[0].rect.height<=48, 'Navigation keeps content first')
    result.operations.push({action:'compact-navigation-touch-geometry',values})
  }
  await geometry(); await capture('01-mobile-discussion-390-dark')
  await require('./thread-discovery.cjs')({ win, read, until, tap, button, capture, result })
  await button('Threads')
  await until('document.querySelector("[data-mote-threads]")?.innerText.includes("比较两个实验方向")')
  assert.equal(await read('document.querySelector("[data-mote-work-event]").dataset.moteWorkEvent'), 'original-research-event')
  assert.equal(await read('document.querySelector(".mobile-mote-threads [data-mote-member=session-mote]")'), null, 'Other Agents exclude the confirmed Main')
  await capture('02-mobile-threads-390-dark')
  await button('事件历史'); if (await read('document.querySelector(".mobile-mote-threads .mote-work-event__summary").getAttribute("aria-expanded")!=="true"')) await tap('.mobile-mote-threads .mote-work-event__summary', 'Expand same original event')
  await until('document.querySelector("[data-mote-work-event]")?.innerText.includes("三份样本已读")')
  await capture('03-mobile-event-history-390-dark')
  assert.equal(await read('document.querySelector("[contenteditable=true]")===window.moteOriginalEditor'), true, 'Hidden original editor stays mounted')
  await button('继续原工作')
  await until('mobileProductScene.facts().record.selectedSessionId==="session-waiting"')
  await capture('04-mobile-original-thread-390-dark')
  await button('Discussion')
  await until('mobileProductScene.facts().record.selectedSessionId==="session-mote"')
  assert.equal(await read('document.querySelector("[contenteditable=true]").textContent'), draft)
  await read('mobileProductScene.replaceMoteMain()')
  await button('查看本 Mote 团队'); await button('刷新本 Mote 团队', '[role=dialog]'); await button('关闭面板', '[role=dialog]')
  await until('document.querySelector(".mobile-mote-main-handoff")?.innerText.includes("主 Agent 已更换")')
  await capture('05-mobile-retained-A-after-rotation-390-dark')
  await button('返回当前主对话')
  await until('mobileProductScene.facts().record.selectedSessionId==="session-waiting"')
  const prior = await read('(()=>{const n=document.querySelector(".mote-conversation__source");return {open:n?.open,text:n?.textContent}})()')
  assert.equal(prior.open, false)
  assert.ok(prior.text.includes('消息切点')&&prior.text.includes('其他工作'))
  result.operations.push({action:'prior-main-whole-session-closed-source',...prior})
  await resize(320,760); await read('mobileProductScene.setAppearance("light")'); await geometry(); await capture('06-mobile-discussion-B-320-light')
  await button('Threads'); await capture('07-mobile-threads-320-light')
  await resize(768,920); await geometry(); await capture('08-mobile-threads-768-light')
  await button('Discussion'); await capture('09-mobile-discussion-B-768-light')
  await read('mobileProductScene.unconfirmMoteDialogue()')
  await button('查看本 Mote 团队'); await button('刷新本 Mote 团队', '[role=dialog]'); await button('关闭面板', '[role=dialog]')
  await until('document.querySelector(".mote-conversation__issue")?.textContent.includes("原主对话读取暂不可用")')
  await resize(390,844); await capture('10-mobile-retained-unknown-390-light')
  assert.equal(await read('mobileProductScene.facts().record.conversation.drafts.find(([key])=>key.includes("session-mote"))?.[1]'), draft)
  const calls = await read('mobileProductScene.facts().calls')
  assert.equal(calls.filter(call=>["agent.input.submit","space.mote.dialogue.input.submit","message.dispatch"].includes(call.method)).length,0)
  result.operations.push({action:'original-draft-and-no-input',draft,calls})
}
