const assert = require('node:assert/strict')
module.exports = async ({ win, read, until, resize, tap, button, capture, result }) => {
  await read('mobileProductScene.prepareFocusState()')
  await button('Focus', '.mobile-navigation')
  await until('!!document.querySelector(".mobile-needs-you-ticket")')
  const middle = async (selector, name) => {
    const frame = await read(`(()=>{const nodes=[...document.querySelectorAll(${JSON.stringify(selector)})];window.chromeMotionAnimations=nodes.flatMap(node=>node.getAnimations());return chromeMotionAnimations.map(a=>{const duration=Number(a.effect.getTiming().duration);a.pause();a.currentTime=duration/2;return {name:a.animationName,duration,progress:a.effect.getComputedTiming().progress}})})()`)
    assert.ok(frame.length > 0 && frame.every(value => value.progress > 0 && value.progress < 1), 'An actual loaded animation owns the captured intermediate frame')
    assert.equal(await read('getComputedStyle(document.documentElement).overflowX'), 'hidden', 'The viewport clips the translated intermediate frame')
    await capture(name, { motion: true })
    await read('chromeMotionAnimations.forEach(animation=>animation.play())')
    await until('!document.querySelector(".mobile-main[data-motion]")')
    result.operations.push({ action: 'rendered-motion-midpoint', selector, frame })
  }
  await resize(390, 844)
  await tap('.mobile-needs-you-ticket', 'Open the original request with screen motion')
  await middle('.mobile-main', 'motion-conversation-push-390')
  await tap('.mobile-header [data-mobile-back]', 'Return to the original directory')
  await middle('.mobile-main, .mobile-navigation-bar', 'motion-root-pop-and-bar-390')
  await tap('.mobile-spatial-panel .mobile-header-menu', 'Open the original drawer')
  await middle('.mobile-drawer, .mobile-drawer-backdrop', 'motion-drawer-390')
  await button('关闭面板', '[role=dialog]')
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  for (const width of [320, 390]) {
    await resize(width, 760)
    await tap('.mobile-needs-you-ticket', 'Open the original request with reduced motion')
    assert.equal(await read('getComputedStyle(document.querySelector(".mobile-main")).animationName'), 'none')
    await capture('motion-reduced-conversation-' + width)
    if (width === 320) {
      const name = await read(`(()=>{const n=document.querySelector('.mobile-session-title');window.narrowOriginalEditor=document.querySelector('.mobile-conversation-panel:not([hidden]) [contenteditable=true]');return {text:n.textContent,width:n.clientWidth,full:n.scrollWidth}})()`)
      assert.ok(name.width >= name.full, 'The short original Agent name stays readable beside its avatar')
      await button('当前对话操作', '.mobile-header')
      await capture('motion-narrow-goal-menu-320')
      await button('目标与结果', '[role=dialog]')
      await until('!!document.querySelector(".mobile-goal-panel:not([hidden])")')
      assert.equal(await read('!!document.querySelector(".mobile-navigation-bar")'), false)
      await tap('.mobile-header [data-mobile-back]', 'Return from Goal work to the visible More trigger')
      await until('!!document.querySelector(".mobile-conversation-panel:not([hidden])")')
      await until(`document.activeElement===document.querySelector('.mobile-header [aria-label="当前对话操作"]')`)
      assert.equal(await read('document.querySelector(".mobile-conversation-panel:not([hidden]) [contenteditable=true]")===narrowOriginalEditor'), true)
    }
    await tap('.mobile-header [data-mobile-back]', 'Return with reduced motion')
    assert.equal(await read('getComputedStyle(document.querySelector(".mobile-navigation-bar")).animationName'), 'none')
    await tap('.mobile-spatial-panel .mobile-header-menu', 'Open the drawer with reduced motion')
    assert.equal(await read('getComputedStyle(document.querySelector(".mobile-drawer")).animationName'), 'none')
    await capture('motion-reduced-drawer-' + width)
    await button('关闭面板', '[role=dialog]')
  }
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [] })
  assert.equal(await read('mobileProductScene.facts().calls.filter(call=>["sdk.ensureAgentContinuity","agent.open","sdk.submitAgentPrompt","sdk.respondAgentInteraction"].includes(call.method)).length'), 0)
}
